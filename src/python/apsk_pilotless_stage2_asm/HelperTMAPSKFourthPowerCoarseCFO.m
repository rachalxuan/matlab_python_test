function [cfoHz,info] = HelperTMAPSKFourthPowerCoarseCFO(x,symbolRateHz,options)
%HELPERTMAPSKFOURTHPOWERCOARSECFO Pilotless APSK coarse-CFO acquisition.
%
%   [CFOHZ,INFO] = HelperTMAPSKFourthPowerCoarseCFO(X,RS,OPTIONS)
%
% X is a one-sample/symbol 16/32APSK stream after timing recovery.  Despite
% the historical function name, the exponent is configurable.  For a
% multi-ring APSK constellation it should be the least common multiple of
% the number of points on the selected rings (12 for CCSDS 16APSK or the
% inner+middle rings of 32APSK; 48 for all 32APSK rings), not simply the
% four-fold rotational-ambiguity order. Raising a
% unit-magnitude stream to this order removes the data phase and turns a
% carrier offset into a spectral line at PowerOrder times the CFO.
%
% OPTIONS fields:
%   AcquisitionSymbols = 4096 % fitting budget; reserve up to as many for validation
%   FFTLength          = 65536
%   MaxCFOHz           = 200e3
%   MinConfidenceDB    = 6
%   UseUnitMagnitude   = true
%   PowerOrder         = 4  % caller selects 12/48 for CCSDS APSK
%   RadiusMin          = -Inf
%   RadiusMax          = +Inf  % optional ring partition before x^M
%   MinSelectedSymbols = 64
%   RangeToleranceHz   = NaN   % auto = half one interpolated CFO bin
%   VerifyOnHoldout    = false % up to four peaks, independent second-half check
%
% The estimate is feed-forward and does not use pilots, ASM or transmitted
% bits.  A three-point parabolic interpolation around the FFT peak reduces
% bin quantization error.

if nargin < 3 || isempty(options)
    options = struct();
end

x = complex(x(:));
Rs = double(symbolRateHz);
if isempty(x) || ~isfinite(Rs) || Rs <= 0
    error('HelperTMAPSKFourthPowerCoarseCFO:InvalidInput', ...
        'X must be nonempty and symbolRateHz must be positive.');
end

requestedFitSymbols = max(64,round(localNumber(options,'AcquisitionSymbols',4096)));
verifyOnHoldout = localLogical(options,'VerifyOnHoldout',false);
nUse = min(numel(x),requestedFitSymbols*(1+double(verifyOnHoldout)));
maxCFOHz = max(0,localNumber(options,'MaxCFOHz',200e3));
minConfidenceDB = localNumber(options,'MinConfidenceDB',6);
useUnitMagnitude = localLogical(options,'UseUnitMagnitude',true);
powerOrder = max(1,round(localNumber(options,'PowerOrder',4)));
radiusMin = localNumber(options,'RadiusMin',-inf);
radiusMax = localNumber(options,'RadiusMax',inf);
minSelectedSymbols = max(8,round(localNumber(options, ...
    'MinSelectedSymbols',64)));

fftLengthRequested = max(1024,round(localNumber(options,'FFTLength',65536)));
nfft = 2^nextpow2(max(fftLengthRequested,nUse));

u = x(1:nUse);
selectionMask = abs(u) >= radiusMin & abs(u) <= radiusMax;
nSelected = nnz(selectionMask);
if useUnitMagnitude
    selectedMagnitude = abs(u(selectionMask));
    if isempty(selectedMagnitude)
        amplitudeFloor = sqrt(eps);
    else
        amplitudeFloor = max(sqrt(eps),1e-3*median(selectedMagnitude));
    end
    u(selectionMask) = u(selectionMask) ./ ...
        max(abs(u(selectionMask)),amplitudeFloor);
else
    if nSelected > 0
        u(selectionMask) = u(selectionMask) / ...
            sqrt(mean(abs(u(selectionMask)).^2)+eps);
    end
end

% Ring selection is rotation invariant and therefore safe before carrier
% acquisition. Keeping the original time indices (zeros for other rings)
% preserves the carrier-tone frequency while the random gating contributes
% only a broadband floor. This avoids forcing 32APSK through x^48 merely to
% remove all three rings at once, which would collapse its unambiguous CFO
% range to roughly +/-Rs/96.
z = complex(zeros(size(u)));
z(selectionMask) = u(selectionMask).^powerOrder;
% A maximum over many FFT bins is NOT independent evidence of a tone.
% Reserve samples before selecting the peak; the validation block never
% searches frequencies or contributes to candidate generation. It only
% validates/ranks the fixed candidates generated by the fitting block.
fitCount = nUse;
if verifyOnHoldout
    fitCount = min(requestedFitSymbols,floor(nUse/2));
end
if fitCount > 1
    window = 0.5 - 0.5*cos(2*pi*(0:fitCount-1)'/(fitCount-1));
else
    window = 1;
end
spectrum = abs(fftshift(fft(z(1:fitCount).*window,nfft))).^2;
frequencyHz = ((-nfft/2):(nfft/2-1))'*(Rs/nfft);

unambiguousMaxCFOHz = 0.499*Rs/powerOrder;
effectiveMaxCFOHz = min(maxCFOHz,unambiguousMaxCFOHz);
maxRaisedPowerHz = powerOrder*effectiveMaxCFOHz;
searchMask = abs(frequencyHz) <= maxRaisedPowerHz;
searchIndices = find(searchMask);
if isempty(searchIndices)
    error('HelperTMAPSKFourthPowerCoarseCFO:EmptySearch', ...
        'The configured CFO search interval is empty.');
end

candidateCount = 1;
if verifyOnHoldout, candidateCount = 4; end
candidateHz = nan(candidateCount,1);
candidatePower = zeros(candidateCount,1);
candidateFloor = zeros(candidateCount,1);
candidateConfidence = nan(candidateCount,1);
validationStatistics = nan(candidateCount,1);
% Account for testing several independently selected frequencies. This
% nominal false-alarm budget is not a calibrated probability in a fading H.
validationThreshold = -log(1e-3/candidateCount);
validationSelected = 0;
workSpectrum = spectrum;
workSpectrum(~searchMask) = -inf;
for k = 1:candidateCount
    [candidatePower(k),peakIndex] = max(workSpectrum);
    if ~isfinite(candidatePower(k)), break; end
    delta = 0;
    if peakIndex > 1 && peakIndex < nfft
        left = log(max(spectrum(peakIndex-1),realmin));
        center = log(max(spectrum(peakIndex),realmin));
        right = log(max(spectrum(peakIndex+1),realmin));
        denom = left - 2*center + right;
        if isfinite(denom) && abs(denom) > eps
            delta = min(max(0.5*(left-right)/denom,-0.5),0.5);
        end
    end
    candidateHz(k) = (frequencyHz(peakIndex)+delta*(Rs/nfft))/powerOrder;
    noiseBins = spectrum(searchIndices(abs(searchIndices-peakIndex)>2));
    if isempty(noiseBins), noiseBins=realmin; end
    candidateFloor(k) = median(noiseBins);
    candidateConfidence(k) = 10*log10(max(candidatePower(k),realmin)/ ...
        max(candidateFloor(k),realmin));
    if verifyOnHoldout
        idx = (fitCount+1:nUse).';
        validationSelected = nnz(selectionMask(idx));
        % Use the same sidelobe suppression as the fitting spectrum. A
        % rectangular validation window can mistake a strong tone's leakage
        % for independent confirmation of a nearby candidate.
        validationWindow = 0.5-0.5*cos(2*pi*(0:numel(idx)-1)'/max(1,numel(idx)-1));
        v = (z(idx).*validationWindow).* ...
            exp(-1j*2*pi*powerOrder*candidateHz(k)*(idx-1)/Rs);
        validationStatistics(k) = abs(sum(v))^2/max(sum(abs(v).^2),realmin);
    end
    % Exclude the Hann main lobe, not just adjacent zero-padded FFT bins.
    workSpectrum(abs((1:nfft)'-peakIndex)<=ceil(2*nfft/fitCount)) = -inf;
end
selected = 1;
validationQualified = true;
validationDominanceDB = NaN;
candidateAccepted = false(candidateCount,1);
if verifyOnHoldout
    candidateAccepted = isfinite(validationStatistics) & ...
        validationStatistics>=validationThreshold & candidateConfidence>=minConfidenceDB;
    [~,selected] = max(validationStatistics);
    others = validationStatistics; others(selected)=0;
    validationDominanceDB = 10*log10(max(validationStatistics(selected),realmin)/ ...
        max(max(others),realmin));
    % A real tone in a time-varying channel can have detectable sidebands.
    % Require dominance over the runner-up, not that every other peak be
    % below the noise threshold. Reuse the existing peak-contrast contract.
    validationQualified = candidateAccepted(selected) && ...
        validationDominanceDB>=minConfidenceDB && ...
        validationSelected>=minSelectedSymbols && ...
        nnz(selectionMask(1:fitCount))>=minSelectedSymbols;
end
cfoHz = candidateHz(selected);
raisedPowerHz = cfoHz*powerOrder;
peakPower = candidatePower(selected);
noiseFloor = candidateFloor(selected);
confidenceDB = candidateConfidence(selected);
validationStatistic = validationStatistics(selected);

rangeToleranceHz = localNumber(options,'RangeToleranceHz',NaN);
if ~isfinite(rangeToleranceHz) || rangeToleranceHz < 0
    rangeToleranceHz = 0.5*Rs/(nfft*powerOrder);
end
qualified = nSelected >= minSelectedSymbols && ...
    isfinite(cfoHz) && ...
    abs(cfoHz) <= effectiveMaxCFOHz + rangeToleranceHz && ...
    isfinite(confidenceDB) && confidenceDB >= minConfidenceDB && ...
    validationQualified;
reason = 'qualified';
if ~qualified
    reason = 'insufficient samples, out of range, or weak FFT peak';
    if ~validationQualified
        reason = 'candidate tone not confirmed on independent holdout';
        if candidateAccepted(selected) && validationDominanceDB<minConfidenceDB
            reason = 'ambiguous CFO: no dominant independent holdout tone';
        end
    end
end

info = struct( ...
    'Applied',true, ...
    'Qualified',qualified, ...
    'Reason',reason, ...
    'VerifyOnHoldout',verifyOnHoldout, ...
    'CandidateSymbols',fitCount, ...
    'ValidationSymbols',nUse-fitCount, ...
    'ValidationSelectedSymbols',validationSelected, ...
    'ValidationStatistic',validationStatistic, ...
    'ValidationThreshold',validationThreshold, ...
    'ValidationQualified',validationQualified, ...
    'ValidationDominanceDB',validationDominanceDB, ...
    'CandidateCFOHz',candidateHz, ...
    'CandidateConfidenceDB',candidateConfidence, ...
    'CandidateValidationStatistics',validationStatistics, ...
    'CandidateAccepted',candidateAccepted, ...
    'SelectedCandidate',selected, ...
    'AcquisitionSymbols',nUse, ...
    'FFTLength',nfft, ...
    'MaxCFOHz',maxCFOHz, ...
    'EffectiveMaxCFOHz',effectiveMaxCFOHz, ...
    'UnambiguousMaxCFOHz',unambiguousMaxCFOHz, ...
    'RangeToleranceHz',rangeToleranceHz, ...
    'PowerOrder',powerOrder, ...
    'RaisedPowerPeakHz',raisedPowerHz, ...
    'FourthPowerPeakHz',raisedPowerHz, ...
    'CFOHz',cfoHz, ...
    'PeakPower',peakPower, ...
    'NoiseFloor',noiseFloor, ...
    'ConfidenceDB',confidenceDB, ...
    'UseUnitMagnitude',useUnitMagnitude, ...
    'RadiusMin',radiusMin, ...
    'RadiusMax',radiusMax, ...
    'SelectedSymbols',nSelected, ...
    'SelectionFraction',nSelected/max(1,nUse), ...
    'MinSelectedSymbols',minSelectedSymbols);
end

function value = localNumber(s,name,defaultValue)
value = defaultValue;
if isstruct(s) && isfield(s,name) && ~isempty(s.(name))
    raw = s.(name);
    if isnumeric(raw) || islogical(raw)
        value = double(raw(1));
    else
        value = str2double(string(raw));
    end
end
end

function value = localLogical(s,name,defaultValue)
value = logical(defaultValue);
if ~(isstruct(s) && isfield(s,name) && ~isempty(s.(name)))
    return;
end
raw = s.(name);
if islogical(raw) || isnumeric(raw)
    value = logical(raw(1));
else
    text = lower(strtrim(string(raw)));
    value = any(text == ["true","1","yes","on"]);
end
end
