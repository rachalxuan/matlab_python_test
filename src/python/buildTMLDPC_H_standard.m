function [H, meta] = buildTMLDPC_H_standard(k, invr)
%BUILDTMLDPC_H_STANDARD Build the CCSDS AR4JA sparse parity-check matrix.
%   This first implementation covers the ordinary-TM rate-1/2 family with
%   information lengths 1024, 4096, and 16384 bits.  H includes the final M
%   punctured columns defined by CCSDS 131.0-B.  The transmitted codeword is
%   therefore H(:,1:meta.TransmittedLength); the decoder must append M
%   zero-LLR punctured variables before belief-propagation decoding.

    validateattributes(k, {'numeric'}, ...
        {'scalar','integer','positive'}, mfilename, 'k');
    validateattributes(invr, {'numeric'}, ...
        {'scalar','real','finite','positive'}, mfilename, 'invr');
    if abs(double(invr) - 2) > 1e-12
        error('buildTMLDPC_H_standard:UnsupportedRate', ...
            'The standard sparse decoder currently supports rate 1/2 only.');
    end

    M = double(k) / 2;
    supportedM = [128 256 512 1024 2048 4096 8192];
    mIndex = find(supportedM == M, 1);
    if isempty(mIndex) || ~ismember(double(k), [1024 4096 16384])
        error('buildTMLDPC_H_standard:UnsupportedInformationLength', ...
            'Unsupported CCSDS rate-1/2 information length k=%d.', k);
    end

    theta = [3 0 1 2 2 3 0 1];
    phi0 = [ ...
          1   59   16  160  108  226 1148; ...
         22   18  103  241  126  618 2032; ...
          0   52  105  185  238  404  249; ...
         26   23    0  251  481   32 1807; ...
          0   11   50  209   96  912  485; ...
         10    7   29  103   28  950 1044; ...
          5   22  115   90   59  534  717; ...
         18   25   30  184  225   63  873];
    phi1 = [ ...
          0    0    0    0    0    0    0; ...
         27   32   53  182  375  767 1822; ...
         30   21   74  249  436  227  203; ...
         28   36   45   65  350  247  882; ...
          7   30   47   70  260  284 1989; ...
          1   29    0  141   84  370  957; ...
          8   44   59  237  318  482 1705; ...
         20   29  102   77  382  273 1083];
    phi2 = [ ...
          0    0    0    0    0    0    0; ...
         12   46    8   35  219  254  318; ...
         30   45  119  167   16  790  494; ...
         18   27   89  214  263  642 1467; ...
         10   48   31   84  415  248  757; ...
         16   37  122  206  403  899 1085; ...
         13   41    1  122  184  328 1630; ...
          9   13   69   67  279  518   64];
    phi3 = [ ...
          0    0    0    0    0    0    0; ...
         13   44   35  162  312  285 1189; ...
         19   51   97    7  503  554  458; ...
         14   12  112   31  388  809  460; ...
         15   15   64  164   48  185 1039; ...
         20   12   93   11    7   49 1000; ...
         17    4   99  237  185  101 1265; ...
          4    7   94  125  328   82 1223];
    phi = cat(3, phi0, phi1, phi2, phi3);

    permutations = cell(1, 8);
    row = (0:M-1).';
    quarter = M / 4;
    group = floor(row / quarter);
    for p = 1:8
        phiByGroup = reshape(phi(p, mIndex, :), 4, 1);
        column = quarter * mod(theta(p) + group, 4) + ...
            mod(phiByGroup(group + 1) + row, quarter);
        permutations{p} = sparse(row + 1, column + 1, true, M, M);
    end

    I = speye(M);
    Z = sparse(M, M);
    xor2 = @(a,b) sparse(logical(mod(a + b, 2)));
    xor3 = @(a,b,c) sparse(logical(mod(a + b + c, 2)));

    H = [ ...
        Z, Z, I, Z, xor2(I, permutations{1}); ...
        I, I, Z, I, xor3(permutations{2}, permutations{3}, permutations{4}); ...
        I, xor2(permutations{5}, permutations{6}), Z, ...
           xor2(permutations{7}, permutations{8}), I];
    H = sparse(logical(H));

    meta = struct( ...
        'InformationLength', double(k), ...
        'SubmatrixSize', M, ...
        'FullCodewordLength', 5*M, ...
        'TransmittedLength', 4*M, ...
        'PuncturedLength', M, ...
        'PuncturedIndices', (4*M+1:5*M).');
end
