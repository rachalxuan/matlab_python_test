function outputDir = capture_rrc_pre_apsk_migration_baseline(outputDir)
%CAPTURE_RRC_PRE_APSK_MIGRATION_BASELINE Freeze the supported RRC baseline.
% Captures the seven ordinary linear modulations plus ordinary-TM,
% pilotless 16/32APSK before the APSK pulse-shaping/interface migration.
% This function changes no synchronization or receiver parameters.

repoRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
pythonDir = fullfile(repoRoot,'src','python');
addpath(pythonDir);

if nargin < 1 || isempty(outputDir)
    stamp = datestr(now,'yyyymmdd_HHMMSS');
    outputDir = fullfile(repoRoot,'tmp','baselines', ...
        ['rrc_pre_apsk_migration_' stamp]);
end
if ~exist(outputDir,'dir'), mkdir(outputDir); end

mods = ["BPSK";"QPSK";"8PSK";"OQPSK";"UQPSK"; ...
    "16QAM";"32QAM";"16APSK";"32APSK"];
families = [repmat("ordinary-linear",7,1);repmat("ordinary-TM APSK",2,1)];

base = struct( ...
    'DataPathMode','single', ...
    'symbolRate',10e6, ...
    'sps',8, ...
    'PulseShapingFilter','root raised cosine', ...
    'RolloffFactor',0.35, ...
    'FilterSpanInSymbols',10, ...
    'channelCoding','none', ...
    'NumBytesInTransferFrame',256, ...
    'hasASM',true, ...
    'RandomizerEnabled',false, ...
    'berWarmUpFrames',8, ...
    'berFrames',16, ...
    'excludeBERWarmUpFrames',true, ...
    'noiseMode','off', ...
    'snr',100, ...
    'cfo',0, ...
    'phaseOffset',0, ...
    'delay',0, ...
    'enableHChannel',false, ...
    'enableEqualizer',false, ...
    'WaveformMode','ordinaryTM', ...
    'APSKReceiverMode','pilotless', ...
    'HasTMAPSKPilots',false, ...
    'debugUQPSKTimingInputNormalization',false, ...
    'enableReceiverTimeline',true, ...
    'includeRawData',true, ...
    'captureBaselineData',true, ...
    'remoteMode',false, ...
    'showFigures',false);

template = struct('CaseName',"",'ModType',"",'Family',"", ...
    'Success',false,'BER',NaN,'FER',NaN,'CountedFrames',NaN, ...
    'ExpectedFrames',NaN,'ComparedFrames',NaN,'CoverageComplete',false, ...
    'TailApplied',false,'TailAppendedSamples',NaN,'TxWaveformSamples',NaN, ...
    'PulseShapingFilter',"",'TransmitPulseShapeActual',"", ...
    'ReceivePulseFilterActual',"",'WaveformMode',"",'Error',"");
rows = repmat(template,numel(mods),1);

fprintf('\n========== RRC PRE-APSK-MIGRATION BASELINE ==========\n');
fprintf('Output: %s\n',outputDir);
for k = 1:numel(mods)
    p = base;
    p.modType = char(mods(k));
    p.randomSeed = 2026092500 + k;
    rng(p.randomSeed,'twister');
    fprintf('\n[%d/%d] %s ...\n',k,numel(mods),mods(k));
    logText = evalc('result = run_ccsds_tm_evaluation(p);');

    rows(k).CaseName = sprintf('%02d_%s_RRC_NoH',k,mods(k));
    rows(k).ModType = mods(k);
    rows(k).Family = families(k);
    rows(k).Success = logical(localField(result,'success',false));
    rows(k).BER = double(localField(result,'BER',NaN));
    rows(k).FER = double(localField(result,'FER',NaN));
    rows(k).CountedFrames = double(localField(result,'CountedFrames',NaN));
    rows(k).PulseShapingFilter = string(localField(result, ...
        'PulseShapingFilter',''));
    rows(k).TransmitPulseShapeActual = string(localField(result, ...
        'TransmitPulseShapeActual',''));
    rows(k).ReceivePulseFilterActual = string(localField(result, ...
        'ReceivePulseFilterActual',''));
    rows(k).WaveformMode = string(localField(result,'WaveformMode',''));
    rows(k).Error = string(localField(result,'errorMsg',''));
    if isfield(result,'MeasurementCoverage')
        c = result.MeasurementCoverage;
        rows(k).ExpectedFrames = double(localField(c,'ExpectedFrames',NaN));
        rows(k).ComparedFrames = double(localField(c,'ComparedFrames',NaN));
        rows(k).CoverageComplete = logical(localField(c,'Complete',false));
    end
    if isfield(result,'BurstCompletion')
        b = result.BurstCompletion;
        rows(k).TailApplied = logical(localField(b,'Applied',false));
        rows(k).TailAppendedSamples = double(localField(b,'AppendedSamples',NaN));
    end
    if isfield(result,'BaselineCapture')
        rows(k).TxWaveformSamples = numel(result.BaselineCapture.TxWaveform);
    end

    caseData = struct('Parameters',p,'Result',result,'ConsoleLog',logText); %#ok<NASGU>
    caseFile = fullfile(outputDir,[char(rows(k).CaseName) '.mat']);
    save(caseFile,'caseData','-v7');
    localWriteText(fullfile(outputDir,[char(rows(k).CaseName) '_console.txt']),logText);
    fprintf('  success=%d BER=%g FER=%g coverage=%g/%g tail=%d txSamples=%g\n', ...
        rows(k).Success,rows(k).BER,rows(k).FER,rows(k).ComparedFrames, ...
        rows(k).ExpectedFrames,rows(k).TailApplied,rows(k).TxWaveformSamples);
end

Summary = struct2table(rows); %#ok<NASGU>
writetable(Summary,fullfile(outputDir,'summary.csv'));
[~,gitHead] = system('git rev-parse HEAD');
[gitStatusCode,gitStatus] = system('git status --short');
Manifest = struct( ...
    'SchemaVersion',1, ...
    'Purpose','RRC baseline before APSK pulse-shaping/interface migration', ...
    'CapturedAt',datestr(now,31), ...
    'GitHead',strtrim(gitHead), ...
    'GitStatusAvailable',gitStatusCode==0, ...
    'GitStatus',gitStatus, ...
    'CommonParameters',base, ...
    'Cases',mods, ...
    'Summary',Summary); %#ok<NASGU>
save(fullfile(outputDir,'manifest.mat'),'Manifest','-v7');

readme = sprintf([ ...
    '# RRC pre-APSK-migration baseline\n\n', ...
    'This directory freezes the No-H RRC behavior before later APSK interface changes.\n', ...
    'Each case MAT contains Parameters, Result, ConsoleLog, and Result.BaselineCapture.\n', ...
    'BaselineCapture contains the full TX waveform, reference constellation, raw RX symbols, ', ...
    'coarse waveform, timing output, fine-carrier output, and resolved configuration.\n', ...
    'summary.csv is the quick comparison index; source_snapshot preserves the relevant MATLAB source.\n', ...
    'The UQPSK timing-input normalization diagnostic is OFF in every case.\n']);
localWriteText(fullfile(outputDir,'README.md'),readme);

snapshotDir = fullfile(outputDir,'source_snapshot');
if ~exist(snapshotDir,'dir'), mkdir(snapshotDir); end
sourceFiles = {'run_ccsds_tm_evaluation.m','ccsdsTMWaveformGenerator.m', ...
    'HelperCCSDSTMDemodulator.m','HelperTMPulseShapeConfig.m', ...
    'HelperTMCompleteBurst.m'};
for k = 1:numel(sourceFiles)
    copyfile(fullfile(pythonDir,sourceFiles{k}),fullfile(snapshotDir,sourceFiles{k}));
end

disp(Summary(:,{'ModType','Success','BER','FER','CountedFrames', ...
    'ComparedFrames','ExpectedFrames','CoverageComplete','TailApplied', ...
    'TxWaveformSamples'}));
if ~all(Summary.Success)
    error('capture_rrc_pre_apsk_migration_baseline:CaseFailed', ...
        'One or more baseline cases failed. Files were preserved in %s.',outputDir);
end
valid = Summary.Success & Summary.BER==0 & Summary.FER==0 & ...
    Summary.CountedFrames==base.berFrames & Summary.CoverageComplete & ...
    Summary.TailApplied & Summary.TxWaveformSamples>0 & ...
    Summary.PulseShapingFilter=="root raised cosine" & ...
    Summary.TransmitPulseShapeActual=="root raised cosine" & ...
    Summary.ReceivePulseFilterActual=="root raised cosine matched filter" & ...
    Summary.WaveformMode=="ordinaryTM";
if ~all(valid)
    error('capture_rrc_pre_apsk_migration_baseline:AcceptanceFailed', ...
        ['One or more cases violate the frozen RRC acceptance contract. ', ...
         'Files were preserved in %s.'],outputDir);
end
for k = find(contains(Summary.ModType,"APSK")).'
    caseFile = fullfile(outputDir,[char(Summary.CaseName(k)) '.mat']);
    saved = load(caseFile,'caseData');
    assert(strcmpi(saved.caseData.Result.APSKReceiverMode,'pilotless') && ...
        ~saved.caseData.Parameters.HasTMAPSKPilots, ...
        'APSK baseline must be ordinary-TM pilotless with custom pilots disabled.');
end
fprintf('\nBaseline saved to: %s\n',outputDir);
end

function value = localField(s,name,defaultValue)
value = defaultValue;
if isstruct(s) && isfield(s,name) && ~isempty(s.(name))
    value = s.(name);
end
end

function localWriteText(fileName,textValue)
fid = fopen(fileName,'w');
assert(fid>=0,'Unable to create %s.',fileName);
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
fwrite(fid,textValue,'char');
end
