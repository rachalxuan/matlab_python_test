function localAssertGeneratorRejected(args, expectedIdentifier)
    warningState = warning('query', 'MATLAB:system:nonRelevantProperty');
    warningCleanup = onCleanup(@() warning(warningState));
    warning('off', 'MATLAB:system:nonRelevantProperty');
    generator = ccsdsTMWaveformGenerator(args{:});
    input = zeros(generator.NumInputBits, 1, 'int8');
    localAssertThrows(@() generator(input), expectedIdentifier);
    clear warningCleanup;
end

function tableValue = localModulationCapabilityTable(capabilities)
    modulation = [ ...
        capabilities.SupportedModulations(:); ...
        capabilities.AddNextModulations(:); ...
        capabilities.SeparateDesignModulations(:); ...
        capabilities.NotApplicableModulations(:)];
    status = [ ...
        repmat("SUPPORTED", numel(capabilities.SupportedModulations), 1); ...
        repmat("ADD_NEXT", numel(capabilities.AddNextModulations), 1); ...
        repmat("SEPARATE_DESIGN", numel(capabilities.SeparateDesignModulations), 1); ...
        repmat("NOT_APPLICABLE", numel(capabilities.NotApplicableModulations), 1)];
    reason = strings(numel(modulation),1);
    reason(status == "SUPPORTED") = ...
        "current equal-rail ordinary-TM implementation";
    reason(modulation == "16APSK" | modulation == "32APSK") = ...
        "ordinary-TM APSK with independent rail coding/randomization and split receiver";
    reason(modulation == "UQPSK") = ...
        "uses separate experimental unequalDualIQ; not equal-rail dualIQ";
    reason(modulation == "4D-8PSK-TCM") = ...
        "grouped trellis state requires a separate rail design";
    reason(status == "NOT_APPLICABLE") = ...
        "one-bit/symbol or special waveform has no independent I/Q bit positions";
    tableValue = table(modulation, status, reason, ...
        'VariableNames', {'Modulation','Status','Reason'});
end

function tableValue = localCodingCapabilityTable(capabilities)
    coding = [ ...
        capabilities.SupportedCodings(:); ...
        capabilities.AddNextCodings(:)];
    status = [ ...
        repmat("SUPPORTED", numel(capabilities.SupportedCodings), 1); ...
        repmat("ADD_NEXT", numel(capabilities.AddNextCodings), 1)];
    reason = strings(numel(coding),1);
    reason(status == "SUPPORTED") = ...
        "current independent per-rail encoder/decoder path";
    reason(coding == "TPC") = ...
        "block-stateless implementation; best next coding candidate";
    reason(coding == "concatenated") = ...
        "requires independent per-rail convolutional buffers and differential state";
    tableValue = table(coding, status, reason, ...
        'VariableNames', {'Coding','Status','Reason'});
end

function localAssertThrows(functionHandle, expectedIdentifier)
    try
        functionHandle();
    catch exception
        localRequire(strcmp(exception.identifier, expectedIdentifier), ...
            sprintf('Expected error "%s", got "%s": %s', ...
                expectedIdentifier, exception.identifier, exception.message));
        return;
    end
    error('run_tm_data_path_contract_tests:ExpectedErrorNotThrown', ...
        'Expected error "%s" was not thrown.', expectedIdentifier);
end

function localRequire(condition, message)
    if ~condition
        error('run_tm_data_path_contract_tests:ContractViolation', '%s', message);
    end
end
