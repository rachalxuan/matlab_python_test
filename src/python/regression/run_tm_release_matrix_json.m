function cfg = localMergeOptions(cfg, userOpts)
    names = fieldnames(userOpts);
    for k = 1:numel(names)
        if ~isfield(cfg, names{k})
            error('run_tm_release_matrix_json:UnknownOption', ...
                'Unknown option "%s".', names{k});
        end
        cfg.(names{k}) = userOpts.(names{k});
    end
    if isempty(cfg.OutputDir)
        cfg.OutputDir = fullfile( ...
            'E:/web_code/react/fft_project/react-fft/artifacts/ccsds/tm_release', ...
            char(cfg.RunId));
    end
    cfg.OutputDir = char(cfg.OutputDir);
    cfg.Profile = lower(string(cfg.Profile));
    cfg.SeedMode = char(string(cfg.SeedMode));
    cfg.Resume = logical(cfg.Resume);
    cfg.RerunFailed = logical(cfg.RerunFailed);
    cfg.DryRun = logical(cfg.DryRun);
    cfg.FailOnFailure = logical(cfg.FailOnFailure);
    cfg.Verbose = logical(cfg.Verbose);
end

function [cases, plan] = localBuildCases(cfg)
    cases = localEmptyCases();
    plan = struct('Single',0,'DualIQ',0,'UnequalDualIQ',0, ...
        'NoHChannels',0,'HChannels',0,'Codings',0,'Randomizers',0);

    channels = localBuildChannels(cfg);
    codings = localBuildCodings(cfg);
    randomizers = cfg.RandomizerCases;
    plan.NoHChannels = nnz(~[channels.HEnabled]);
    plan.HChannels = nnz([channels.HEnabled]);
    plan.Codings = numel(codings);
    plan.Randomizers = numel(randomizers);

    for ich = 1:numel(channels)
        channel = channels(ich);

        if cfg.IncludeSinglePath
            mods = localCellstr(cfg.SingleModulations);
            for im = 1:numel(mods)
                for ic = 1:numel(codings)
                    for ir = 1:numel(randomizers)
                        cases(end+1,1) = localMakeCase(cfg, channel, ...
                            'single', mods{im}, codings(ic), randomizers(ir)); %#ok<AGROW>
                        plan.Single = plan.Single + 1;
                    end
                end
            end
        end

        if cfg.IncludeDualIQPath
            mods = localCellstr(cfg.DualIQModulations);
            for im = 1:numel(mods)
                for ic = 1:numel(codings)
                    for ir = 1:numel(randomizers)
                        cases(end+1,1) = localMakeCase(cfg, channel, ...
                            'dualIQ', mods{im}, codings(ic), randomizers(ir)); %#ok<AGROW>
                        plan.DualIQ = plan.DualIQ + 1;
                    end
                end
            end
        end

        if cfg.IncludeUnequalUQPSK
            for ic = 1:numel(codings)
                for ir = 1:numel(randomizers)
                    cases(end+1,1) = localMakeCase(cfg, channel, ...
                        'unequalDualIQ', 'UQPSK', codings(ic), randomizers(ir)); %#ok<AGROW>
                    plan.UnequalDualIQ = plan.UnequalDualIQ + 1;
                end
            end
        end
    end
end

function channels = localBuildChannels(cfg)
    channels = struct('Name',{},'HEnabled',{},'File',{});
    if cfg.IncludeNoH
        channels(end+1) = struct('Name','noH','HEnabled',false,'File',''); %#ok<AGROW>
    end
    if cfg.IncludeH
        hCases = cfg.HModelCases;
        if iscell(hCases) && size(hCases,2) ~= 2
            error('run_tm_release_matrix_json:InvalidHModelCases', ...
                'HModelCases must be an N-by-2 cell array: {label, file}.');
        end
        for k = 1:size(hCases,1)
            label = char(string(hCases{k,1}));
            filePath = char(string(hCases{k,2}));
            if exist(filePath,'file') ~= 2
                error('run_tm_release_matrix_json:MissingHFile', ...
                    'H file does not exist: %s', filePath);
            end
            channels(end+1) = struct('Name',label, ...
                'HEnabled',true,'File',filePath); %#ok<AGROW>
        end
    end
end

function codings = localBuildCodings(cfg)
    codings = struct('Coding',{},'Rate',{},'TFBytes',{},'Extra',{});
    if cfg.IncludeUncoded
        codings(end+1) = localCoding('none','-',1115,struct()); %#ok<AGROW>
    end
    if cfg.IncludeRS
        codings(end+1) = localCoding('RS','223/255',1115,struct( ...
            'RSMessageLength',223,'RSInterleavingDepth',1, ...
            'IsRSMessageShortened',false)); %#ok<AGROW>
    end
    if cfg.IncludeConvolutional
        rates = localCellstr(cfg.ConvolutionalRates);
        for k = 1:numel(rates)
            rate = rates{k};
            tfBytes = 1115;
            if strcmp(rate,'5/6'), tfBytes = 1116; end
            if strcmp(rate,'7/8'), tfBytes = 1123; end
            codings(end+1) = localCoding('convolutional',rate,tfBytes, ...
                struct('ConvolutionalCodeRate',rate)); %#ok<AGROW>
        end
    end
    if cfg.IncludeLDPC
        rates = localCellstr(cfg.LDPCRates);
        for k = 1:numel(rates)
            rate = rates{k};
            codings(end+1) = localCoding('LDPC',rate,1115,struct( ...
                'CodeRate',rate,'NumBitsInInformationBlock',1024, ...
                'IsLDPCOnSMTF',false)); %#ok<AGROW>
        end
    end
    if cfg.IncludeTurbo
        rates = localCellstr(cfg.TurboRates);
        for k = 1:numel(rates)
            rate = rates{k};
            codings(end+1) = localCoding('turbo',rate,1115,struct( ...
                'CodeRate',rate,'NumBitsInInformationBlock',1784)); %#ok<AGROW>
        end
    end
end

function c = localCoding(coding, rate, tfBytes, extra)
    c = struct('Coding',char(coding),'Rate',char(rate), ...
        'TFBytes',double(tfBytes),'Extra',extra);
end

function randomizers = localRandomizers()
    randomizers = struct('Label',{},'Enabled',{},'Position',{});
    randomizers(end+1) = struct('Label','off','Enabled',false, ...
        'Position','afterEncoding'); %#ok<AGROW>
    randomizers(end+1) = struct('Label','after','Enabled',true, ...
        'Position','afterEncoding'); %#ok<AGROW>
    randomizers(end+1) = struct('Label','before','Enabled',true, ...
        'Position','beforeEncoding'); %#ok<AGROW>
end

