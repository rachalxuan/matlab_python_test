function T = run_tm_release_matrix_json(userOpts)
%RUN_TM_RELEASE_MATRIX_JSON Capability-driven ordinary-TM release matrix.
%
% This entry point keeps the old sweep runners untouched and builds only
% combinations that are valid for the selected data path:
%   single         : BPSK/QPSK/OQPSK/8PSK/16QAM/32QAM/MSK/GMSK
%   dualIQ         : QPSK/OQPSK/8PSK/16QAM/32QAM/16APSK/32APSK
%   unequalDualIQ  : UQPSK only
%
% It expands RS, all supported convolutional/LDPC/Turbo rates, and the
% off/after/before randomizer modes.  Results are checkpointed by
% reg_run_cases and exported as a metrics-only JSON summary.
%
% Example:
%   opts = struct('Profile','h-functional', ...
%       'SymbolRate',20e6,'SamplesPerSymbol',8,'BERFrames',16);
%   T = run_tm_release_matrix_json(opts);

    if nargin < 1 || isempty(userOpts)
        userOpts = struct();
    end
    if ~isstruct(userOpts)
        error('run_tm_release_matrix_json:InvalidOptions', ...
            'userOpts must be a struct.');
    end

    thisDir = fileparts(mfilename('fullpath'));
    srcDir = fileparts(thisDir);
    addpath(thisDir, '-begin');
    addpath(srcDir);

    profile = string(localOption(userOpts, 'Profile', "h-functional"));
    cfg = localDefaults(profile);
    cfg = localMergeOptions(cfg, userOpts);
    cfg.Profile = lower(string(cfg.Profile));

    [cases, plan] = localBuildCases(cfg);
    fprintf('\n===== TM release matrix plan =====\n');
    fprintf('Profile: %s\n', char(cfg.Profile));
    fprintf('Cases: %d\n', numel(cases));
    fprintf('Paths: single=%d dualIQ=%d unequalDualIQ=%d\n', ...
        plan.Single, plan.DualIQ, plan.UnequalDualIQ);
    fprintf('Channels: noH=%d H=%d | codings=%d | randomizers=%d\n', ...
        plan.NoHChannels, plan.HChannels, plan.Codings, plan.Randomizers);

    runnerOpts = struct( ...
        'OutputDir', cfg.OutputDir, ...
        'RunId', cfg.RunId, ...
        'PlanVersion', "tm-release-matrix-v1-" + cfg.Profile, ...
        'Resume', cfg.Resume, ...
        'MaxNewCases', cfg.MaxNewCases, ...
        'RerunFailed', cfg.RerunFailed, ...
        'BaseSeed', cfg.BaseSeed, ...
        'SeedMode', cfg.SeedMode, ...
        'CaseIds', cfg.CaseIds, ...
        'DryRun', cfg.DryRun, ...
        'FailOnFailure', cfg.FailOnFailure, ...
        'Verbose', cfg.Verbose);

    [T, state] = reg_run_cases("tm_release_matrix", cases, runnerOpts);
    T = localAttachMetadata(T, cases, cfg);

    if ~cfg.DryRun
        outputDir = char(state.OutputDir);
        csvPath = fullfile(outputDir, 'tm_release_matrix_summary.csv');
        jsonPath = fullfile(outputDir, 'tm_release_matrix_summary.json');
        localWriteTable(T, csvPath);
        localWriteJson(T, cfg, plan, jsonPath);

        fprintf('\n===== TM release matrix result =====\n');
        fprintf('Total=%d FunctionalPass=%d PerformancePass=%d ERROR=%d\n', ...
            height(T), nnz(T.FunctionalPass), nnz(T.PerformancePass), ...
            nnz(T.Status == "ERROR"));
        fprintf('Checkpoint: %s\n', fullfile(outputDir, 'checkpoint.mat'));
        fprintf('CSV       : %s\n', csvPath);
        fprintf('JSON      : %s\n', jsonPath);
    end
end

