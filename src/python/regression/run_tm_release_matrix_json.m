function T = localAttachMetadata(T, cases, cfg)
    n = height(T);
    T.DataPathMode = strings(n,1);
    T.Modulation = strings(n,1);
    T.Coding = strings(n,1);
    T.Rate = strings(n,1);
    T.RandomizerLabel = strings(n,1);
    T.RandomizerEnabled = false(n,1);
    T.RandomizerFECPosition = strings(n,1);
    T.ChannelProfile = strings(n,1);
    T.HEnabled = false(n,1);
    T.FunctionalPass = false(n,1);
    T.FunctionalStatus = strings(n,1);
    T.PerformancePass = logical(T.Pass);
    T.PerformanceStatus = string(T.Status);
    T.SNR_dB = repmat(double(cfg.SNR),n,1);

    for k = 1:n
        meta = cases(k).Meta;
        T.DataPathMode(k) = meta.DataPathMode;
        T.Modulation(k) = meta.Modulation;
        T.Coding(k) = meta.Coding;
        T.Rate(k) = meta.Rate;
        T.RandomizerEnabled(k) = meta.RandomizerEnabled;
        T.RandomizerFECPosition(k) = meta.RandomizerFECPosition;
        T.ChannelProfile(k) = meta.ChannelProfile;
        T.HEnabled(k) = meta.HEnabled;

        if T.Status(k) == "ERROR"
            T.FunctionalStatus(k) = "ERROR";
        elseif isfinite(T.LockRate(k)) && T.LockRate(k) >= cfg.MinLockRate && ...
                isfinite(T.CountedFrames(k)) && T.CountedFrames(k) >= 1
            T.FunctionalPass(k) = true;
            T.FunctionalStatus(k) = "PASS";
        else
            T.FunctionalStatus(k) = "FAIL";
        end
    end

    leading = {'CaseId','Status','Pass','FunctionalStatus','FunctionalPass', ...
        'PerformanceStatus','PerformancePass','DataPathMode','Modulation', ...
        'Coding','Rate','RandomizerEnabled','RandomizerFECPosition', ...
        'ChannelProfile','HEnabled','SNR_dB'};
    T = movevars(T, leading, 'Before', 1);
end

function localWriteJson(T, cfg, plan, pathValue)
    payload = struct( ...
        'Suite',"tm_release_matrix", ...
        'Profile',string(cfg.Profile), ...
        'GeneratedAt',string(datestr(now,'yyyy-mm-dd HH:MM:SS')), ...
        'Plan',plan, ...
        'Cases',table2struct(T));
    outputDir = fileparts(pathValue);
    if ~isfolder(outputDir), mkdir(outputDir); end
    fid = fopen(pathValue,'w');
    assert(fid >= 0, 'Cannot create JSON file: %s', pathValue);
    cleanup = onCleanup(@() fclose(fid));
    fprintf(fid,'%s',jsonencode(payload));
    clear cleanup;
end

function localWriteTable(T, pathValue)
    outputDir = fileparts(pathValue);
    if ~isfolder(outputDir), mkdir(outputDir); end
    writetable(T,pathValue);
end

function cases = localEmptyCases()
    cases = struct('Id',{},'Name',{},'Category',{}, ...
        'Params',{},'Expected',{},'Meta',{});
end

function values = localCellstr(value)
    if iscell(value)
        values = cellfun(@char,value,'UniformOutput',false);
    else
        values = cellstr(string(value));
    end
end

function value = localOption(s,name,defaultValue)
    value = defaultValue;
    if isstruct(s) && isfield(s,name) && ~isempty(s.(name))
        value = s.(name);
    end
end

function id = localId(text)
    id = lower(regexprep(string(text),'[^a-zA-Z0-9]+','.'));
    id = strip(id,'.');
end
