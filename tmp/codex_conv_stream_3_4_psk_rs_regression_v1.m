% CODEX_CONV_STREAM_3_4_PSK_RS_REGRESSION_V1
% Extends the opt-in continuous 3/4 receiver without changing its legacy
% default route.  The two controls are deliberately No-H/no-noise:
%   1) 8PSK + convolutional 3/4 with a non-aligned TM-frame length.
%   2) QPSK + RS(255,223), I=1 + convolutional 3/4.  After continuous
%      Viterbi decoding the receiver finds raw ASM, extracts a 2040-bit RS
%      codeword, invokes ccsdsRSDecode, and returns the 1784-bit TM frame.

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);
addpath(fullfile(projectDir,'src','python'));

if ~exist('ConvStream34PSKRSOptions','var') || ...
        ~isstruct(ConvStream34PSKRSOptions)
    ConvStream34PSKRSOptions = struct;
end
warmupFrames = localNumber(ConvStream34PSKRSOptions, ...
    'WarmUpFrames',8);
measurementFrames = localNumber(ConvStream34PSKRSOptions, ...
    'MeasurementFrames',120);
debugReceiver = localLogical(ConvStream34PSKRSOptions, ...
    'DebugReceiver',true);

rows = repmat(localEmptyRow(),2,1);
fprintf('\n================ CONV 3/4 PSK + OUTER-RS REGRESSION ================\n');

% 1150 Byte gives 32+1150*8 = 9232 raw bits, and 9232 mod 3 = 1.
p = localBaseOptions('8PSK','convolutional',1150, ...
    warmupFrames,measurementFrames,debugReceiver);
fprintf(['\n[1/2] 8PSK + convolutional 3/4, No-H, TF=1150 Byte\n', ...
    '      raw frame = 32 + 1150*8 = 9232 bits; mod 3 = %d\n'], ...
    mod(32+1150*8,3));
m = run_ccsds_tm_evaluation(p);
rows(1) = localResultRow('8PSK + conv 3/4',m,measurementFrames, ...
    mod(32+1150*8,3),false);
localPrintResult(rows(1),m);

% Full-length RS223, I=1: 32-bit ASM + 255*8-bit RS codeword = 2072 bits.
% The frame is intentionally not aligned to the 3-input-bit puncture period.
p = localBaseOptions('QPSK','concatenated',223, ...
    warmupFrames,measurementFrames,debugReceiver);
p.RSMessageLength = 223;
p.RSInterleavingDepth = 1;
p.IsRSMessageShortened = false;
fprintf(['\n[2/2] QPSK + RS(255,223), I=1 + convolutional 3/4, No-H\n', ...
    '      raw frame = 32 + 255*8 = 2072 bits; mod 3 = %d\n', ...
    '      expected decoded TF = 223*8 = 1784 bits\n'], ...
    mod(32+255*8,3));
m = run_ccsds_tm_evaluation(p);
rows(2) = localResultRow('RS223 I=1 + conv 3/4',m, ...
    measurementFrames,mod(32+255*8,3),true);
localPrintResult(rows(2),m);

ConvStream34PSKRSResults = struct2table(rows);
fprintf('\n================ REGRESSION SUMMARY ================\n');
disp(ConvStream34PSKRSResults);
assert(all(ConvStream34PSKRSResults.Pass), ...
    ['Continuous 3/4 PSK/outer-RS regression failed. Inspect ', ...
     'ConvStream34PSKRSResults.']);
fprintf(['PASS: 8PSK No-H and RS223 I=1 + convolutional 3/4 both passed; ', ...
    'the requested measurement window is %d/%d frames.\n'], ...
    measurementFrames,measurementFrames);

function p = localBaseOptions(modType,channelCoding,tfBytes, ...
        warmupFrames,measurementFrames,debugReceiver)
    p = struct( ...
        'modType',modType, ...
        'channelCoding',channelCoding, ...
        'ConvolutionalCodeRate','3/4', ...
        'ConvolutionalReceiveMode','stream-raw-asm', ...
        'symbolRate',10e6, ...
        'sps',8, ...
        'snr',100, ...
        'noiseMode','off', ...
        'noisePlacement','afterChannel', ...
        'cfo',0, ...
        'phaseOffset',0, ...
        'delay',0, ...
        'RolloffFactor',0.35, ...
        'WaveformMode','ordinaryTM', ...
        'NumBytesInTransferFrame',tfBytes, ...
        'hasASM',true, ...
        'RandomizerEnabled',false, ...
        'RandomizerFECPosition','afterEncoding', ...
        'DataPathMode','single', ...
        'TMDataSource','random', ...
        'PCMFormat','NRZ-L', ...
        'berWarmUpFrames',warmupFrames, ...
        'berFrames',measurementFrames, ...
        'excludeBERWarmUpFrames',true, ...
        'enableHChannel',false, ...
        'HMode','none', ...
        'normalizeHChannel',false, ...
        'enableEqualizer',false, ...
        'equalizerMode','off', ...
        'enableKnownHPreEqualizer',false, ...
        'normalizeEqualizerOutput',false, ...
        'enableConverterChain',false, ...
        'enableADCEquivalent',false, ...
        'inputLevelDbm',-10, ...
        'AGCEnabled',false, ...
        'showFigures',false, ...
        'showPipelineFigure',false, ...
        'showDamageBudgetFigure',false, ...
        'showPowerFigure',false, ...
        'debugContinuousConvReceiver',debugReceiver, ...
        'debugCodedBoundary',false, ...
        'debugPerFrameBERSummary',false, ...
        'seed',7341);
end

function row = localResultRow(caseName,m,measurementFrames,remainder,expectRS)
    coverageComplete = isfield(m,'MeasurementCoverage') && ...
        strcmpi(string(m.MeasurementCoverage.Status),'COMPLETE') && ...
        m.MeasurementCoverage.ComparedFrames == measurementFrames;
    rsApplied = localField(m,'ContinuousConvOuterRSDecodeApplied',false);
    rsUncorrectable = localField(m, ...
        'ContinuousConvOuterRSUncorrectableFrames',NaN);
    pass = logical(m.success) && m.BER == 0 && m.FER == 0 && ...
        coverageComplete && ...
        logical(localField(m,'ContinuousConvReceiverAvailable',false)) && ...
        localField(m,'ContinuousConvLongestGoodASMRun',0) >= 4;
    if expectRS
        pass = pass && logical(rsApplied) && rsUncorrectable == 0;
    end
    row = struct( ...
        'CaseName',string(caseName), ...
        'RawFrameRemainderMod3',remainder, ...
        'Success',logical(m.success), ...
        'ReceiverAvailable',logical(localField(m, ...
            'ContinuousConvReceiverAvailable',false)), ...
        'SelectedOffset',localField(m, ...
            'ContinuousConvSelectedOffset',NaN), ...
        'LongestGoodASMRun',localField(m, ...
            'ContinuousConvLongestGoodASMRun',NaN), ...
        'RecoveredFrames',localField(m, ...
            'ContinuousConvRecoveredFrames',NaN), ...
        'OuterRSDecodeApplied',logical(rsApplied), ...
        'OuterRSUncorrectableFrames',rsUncorrectable, ...
        'BER',m.BER, ...
        'FER',m.FER, ...
        'ComparedFrames',m.MeasurementCoverage.ComparedFrames, ...
        'ExpectedFrames',m.MeasurementCoverage.ExpectedFrames, ...
        'CoverageStatus',string(m.MeasurementCoverage.Status), ...
        'Pass',logical(pass));
end

function localPrintResult(row,m)
    fprintf(['      available=%d drop=%g asmRun=%g recovered=%g ', ...
        'outerRS=%d uncorrectable=%g\n'], ...
        row.ReceiverAvailable,row.SelectedOffset,row.LongestGoodASMRun, ...
        row.RecoveredFrames,row.OuterRSDecodeApplied, ...
        row.OuterRSUncorrectableFrames);
    fprintf(['      BER=%.4g FER=%.4g coverage=%g/%g (%s) -> %s\n'], ...
        row.BER,row.FER,row.ComparedFrames,row.ExpectedFrames, ...
        row.CoverageStatus,localPassLabel(row.Pass));
    if isfield(m,'ContinuousConvOuterRSCorrectedBits')
        fprintf('      outer RS corrected bits=%g\n', ...
            m.ContinuousConvOuterRSCorrectedBits);
    end
end

function value = localField(s,name,defaultValue)
    if isfield(s,name) && ~isempty(s.(name))
        value = s.(name);
    else
        value = defaultValue;
    end
end

function value = localNumber(s,name,defaultValue)
    value = double(localField(s,name,defaultValue));
end

function value = localLogical(s,name,defaultValue)
    value = logical(localField(s,name,defaultValue));
end

function label = localPassLabel(pass)
    if pass
        label = 'PASS';
    else
        label = 'FAIL';
    end
end

function row = localEmptyRow()
    row = struct( ...
        'CaseName',"", ...
        'RawFrameRemainderMod3',NaN, ...
        'Success',false, ...
        'ReceiverAvailable',false, ...
        'SelectedOffset',NaN, ...
        'LongestGoodASMRun',NaN, ...
        'RecoveredFrames',NaN, ...
        'OuterRSDecodeApplied',false, ...
        'OuterRSUncorrectableFrames',NaN, ...
        'BER',NaN, ...
        'FER',NaN, ...
        'ComparedFrames',NaN, ...
        'ExpectedFrames',NaN, ...
        'CoverageStatus',"", ...
        'Pass',false);
end
