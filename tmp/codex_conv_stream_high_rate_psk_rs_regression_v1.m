% CODEX_CONV_STREAM_HIGH_RATE_PSK_RS_REGRESSION_V1
% No-H integration checks beyond the QPSK/plain-convolutional baseline:
% 8PSK non-aligned 5/6 and 7/8, plus the already-scoped RS223 I=1 outer
% decoder.  The RS 7/8 case is an aligned control; RS223 I=1 + 5/6 is the
% non-aligned concatenated proof.

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);
addpath(fullfile(projectDir,'src','python'));

if ~exist('ConvStreamHighRatePSKRSOptions','var') || ...
        ~isstruct(ConvStreamHighRatePSKRSOptions)
    ConvStreamHighRatePSKRSOptions = struct;
end
warmupFrames = localNumber(ConvStreamHighRatePSKRSOptions, ...
    'WarmUpFrames',8);
measurementFrames = localNumber(ConvStreamHighRatePSKRSOptions, ...
    'MeasurementFrames',120);
debugReceiver = localLogical(ConvStreamHighRatePSKRSOptions, ...
    'DebugReceiver',false);

cases = [ ...
    struct('Name',"8PSK + conv 5/6",'Mod',"8PSK", ...
        'Coding',"convolutional",'Rate',"5/6",'TFBytes',1150, ...
        'RawBits',32+1150*8,'ExpectRS',false); ...
    struct('Name',"8PSK + conv 7/8",'Mod',"8PSK", ...
        'Coding',"convolutional",'Rate',"7/8",'TFBytes',1150, ...
        'RawBits',32+1150*8,'ExpectRS',false); ...
    struct('Name',"RS223 I=1 + conv 5/6",'Mod',"QPSK", ...
        'Coding',"concatenated",'Rate',"5/6",'TFBytes',223, ...
        'RawBits',32+255*8,'ExpectRS',true); ...
    struct('Name',"RS223 I=1 + conv 7/8",'Mod',"QPSK", ...
        'Coding',"concatenated",'Rate',"7/8",'TFBytes',223, ...
        'RawBits',32+255*8,'ExpectRS',true)];
rows = repmat(localEmptyRow(),numel(cases),1);

fprintf('\n================ HIGH-RATE PSK + OUTER-RS REGRESSION ================\n');
for iCase = 1:numel(cases)
    c = cases(iCase);
    cfg = ccsdsTMConvolutionalPunctureConfig(c.Rate);
    remainder = mod(c.RawBits,cfg.InputBitsPerPeriod);
    p = localBaseOptions(c.Mod,c.Coding,c.TFBytes,c.Rate, ...
        warmupFrames,measurementFrames,debugReceiver);
    if c.ExpectRS
        p.RSMessageLength = 223;
        p.RSInterleavingDepth = 1;
        p.IsRSMessageShortened = false;
    end
    fprintf('\n[%d/%d] %s, raw=%d bits, remainder=%d/%d\n', ...
        iCase,numel(cases),c.Name,c.RawBits,remainder, ...
        cfg.InputBitsPerPeriod);
    m = run_ccsds_tm_evaluation(p);
    rows(iCase) = localResultRow(c,m,measurementFrames,remainder);
    localPrint(rows(iCase),m);
end

ConvStreamHighRatePSKRSResults = struct2table(rows);
disp(ConvStreamHighRatePSKRSResults);
assert(all(ConvStreamHighRatePSKRSResults.Pass), ...
    'High-rate PSK/outer-RS integration regression failed.');
fprintf('PASS: %d/%d high-rate PSK/outer-RS cases passed.\n', ...
    nnz(ConvStreamHighRatePSKRSResults.Pass), ...
    height(ConvStreamHighRatePSKRSResults));

function p = localBaseOptions(modType,coding,tfBytes,rate, ...
        warmupFrames,measurementFrames,debugReceiver)
p = struct( ...
    'modType',char(modType),'channelCoding',char(coding), ...
    'ConvolutionalCodeRate',char(rate), ...
    'ConvolutionalReceiveMode','stream-raw-asm', ...
    'symbolRate',10e6,'sps',8,'snr',100,'noiseMode','off', ...
    'noisePlacement','afterChannel','cfo',0,'phaseOffset',0,'delay',0, ...
    'RolloffFactor',0.35,'WaveformMode','ordinaryTM', ...
    'NumBytesInTransferFrame',tfBytes,'hasASM',true, ...
    'RandomizerEnabled',false,'RandomizerFECPosition','afterEncoding', ...
    'DataPathMode','single','TMDataSource','random','PCMFormat','NRZ-L', ...
    'berWarmUpFrames',warmupFrames,'berFrames',measurementFrames, ...
    'excludeBERWarmUpFrames',true,'enableHChannel',false,'HMode','none', ...
    'normalizeHChannel',false,'enableEqualizer',false, ...
    'equalizerMode','off','enableKnownHPreEqualizer',false, ...
    'normalizeEqualizerOutput',false,'enableConverterChain',false, ...
    'enableADCEquivalent',false,'inputLevelDbm',-10,'AGCEnabled',false, ...
    'showFigures',false,'showPipelineFigure',false, ...
    'showDamageBudgetFigure',false,'showPowerFigure',false, ...
    'debugContinuousConvReceiver',debugReceiver, ...
    'debugCodedBoundary',false,'debugPerFrameBERSummary',false, ...
    'seed',8765);
end

function row = localResultRow(c,m,measurementFrames,remainder)
coverage = isfield(m,'MeasurementCoverage') && ...
    strcmpi(string(m.MeasurementCoverage.Status),'COMPLETE') && ...
    m.MeasurementCoverage.ComparedFrames==measurementFrames && ...
    m.MeasurementCoverage.UnrecoveredFrames==0 && ...
    m.MeasurementCoverage.RecoveredNotComparedFrames==0;
rsApplied = localField(m,'ContinuousConvOuterRSDecodeApplied',false);
rsBad = localField(m,'ContinuousConvOuterRSUncorrectableFrames',NaN);
pass = logical(m.success) && m.BER==0 && m.FER==0 && coverage && ...
    logical(localField(m,'ContinuousConvReceiverAvailable',false)) && ...
    localField(m,'ContinuousConvLongestGoodASMRun',0)>=4;
if c.ExpectRS, pass=pass && logical(rsApplied) && rsBad==0; end
row = struct('CaseName',c.Name,'CodeRate',c.Rate, ...
    'RawFrameRemainder',remainder,'Success',logical(m.success), ...
    'ReceiverAvailable',logical(localField(m, ...
        'ContinuousConvReceiverAvailable',false)), ...
    'SelectedOffset',localField(m,'ContinuousConvSelectedOffset',NaN), ...
    'LongestGoodASMRun',localField(m, ...
        'ContinuousConvLongestGoodASMRun',NaN), ...
    'RecoveredFrames',localField(m,'ContinuousConvRecoveredFrames',NaN), ...
    'OuterRSDecodeApplied',logical(rsApplied), ...
    'OuterRSUncorrectableFrames',rsBad,'BER',m.BER,'FER',m.FER, ...
    'ComparedFrames',m.MeasurementCoverage.ComparedFrames, ...
    'ExpectedFrames',m.MeasurementCoverage.ExpectedFrames, ...
    'CoverageStatus',string(m.MeasurementCoverage.Status),'Pass',logical(pass));
end

function localPrint(row,m)
fprintf(['  available=%d drop=%g run=%g recovered=%g outerRS=%d ', ...
    'uncorrectable=%g BER=%g FER=%g coverage=%g/%g -> %s\n'], ...
    row.ReceiverAvailable,row.SelectedOffset,row.LongestGoodASMRun, ...
    row.RecoveredFrames,row.OuterRSDecodeApplied, ...
    row.OuterRSUncorrectableFrames,row.BER,row.FER, ...
    row.ComparedFrames,row.ExpectedFrames,localPassLabel(row.Pass));
if isfield(m,'ContinuousConvOuterRSCorrectedBits')
    fprintf('  outer RS corrected bits=%g\n', ...
        m.ContinuousConvOuterRSCorrectedBits);
end
end

function value = localField(s,name,defaultValue)
value=defaultValue;
if isfield(s,name) && ~isempty(s.(name)), value=s.(name); end
end

function value = localNumber(s,name,defaultValue)
value=double(localField(s,name,defaultValue));
end

function value = localLogical(s,name,defaultValue)
value=logical(localField(s,name,defaultValue));
end

function label = localPassLabel(pass)
if pass, label='PASS'; else, label='FAIL'; end
end

function row = localEmptyRow()
row = struct('CaseName',"",'CodeRate',"",'RawFrameRemainder',NaN, ...
    'Success',false,'ReceiverAvailable',false,'SelectedOffset',NaN, ...
    'LongestGoodASMRun',NaN,'RecoveredFrames',NaN, ...
    'OuterRSDecodeApplied',false,'OuterRSUncorrectableFrames',NaN, ...
    'BER',NaN,'FER',NaN,'ComparedFrames',NaN,'ExpectedFrames',NaN, ...
    'CoverageStatus',"",'Pass',false);
end
