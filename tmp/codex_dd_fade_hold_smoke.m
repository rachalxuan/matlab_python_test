clearvars;
clear classes;
rehash;
addpath('E:/web_code/react/fft_project/react-fft/src/python');

rng(20260827,'twister');
ref = [1+1j; 1-1j; -1+1j; -1-1j]/sqrt(2);
x = ref(randi(4,4096,1));
x(1025:1280) = 0.05*x(1025:1280);

gainOpt = struct( ...
    'MagnitudeEstimationMode','power', ...
    'TrackMagnitude',true, ...
    'TrackPhase',false, ...
    'UpdatePowerReference',false, ...
    'PowerReference',1, ...
    'FadePowerTauSymbols',8, ...
    'EnableFadeHold',true, ...
    'FadeEnterDB',-8, ...
    'FadeExitDB',-5, ...
    'HoldEnterBadSymbols',1, ...
    'RecoverGoodSymbols',2, ...
    'Regularization',0, ...
    'MaxInverseGainDB',40, ...
    'Debug',true);
[~,~,gainInfo] = HelperTMComplexGainTracker(x,ref,gainOpt);

eqOpt = struct( ...
    'modType','QPSK', ...
    'adaptiveEqualizerStage','dd', ...
    'adaptiveEqualizerTaps',1, ...
    'adaptiveEqualizerDDPasses',1, ...
    'adaptiveEqualizerDDStep',1e-3, ...
    'adaptiveEqualizerDecisionGate',0.8, ...
    'adaptiveEqualizerDDWindowSymbols',64, ...
    'adaptiveEqualizerDDMinWindowAcceptance',0, ...
    'adaptiveEqualizerEnableFadeHold',true, ...
    'adaptiveEqualizerFadeHoldDB',-8, ...
    'adaptiveEqualizerFadeRecoverDB',-5, ...
    'adaptiveEqualizerFadeDetectorSymbols',16, ...
    'adaptiveEqualizerFadeRecoverWindows',2, ...
    'adaptiveEqualizerQualityGuard',false);
[~,~,eqInfo] = HelperTMBlindCMAEqualizer(x,ref,eqOpt);

fprintf('\n===== unified fade HOLD smoke =====\n');
fprintf('one-tap gain: fade=%d holdEvents=%d recover=%d inverseMax=%+.2f dB\n', ...
    gainInfo.FadeSymbols,gainInfo.HoldEvents,gainInfo.RecoverEvents, ...
    gainInfo.InverseGainMaxObserved_dB);
fprintf('DD windows  : hold=%d fadeHold=%d enter/recover=%d/%d\n', ...
    eqInfo.DDHoldWindows,eqInfo.DDFadeHoldWindows, ...
    eqInfo.DDFadeEnterEvents,eqInfo.DDFadeRecoverEvents);

assert(gainInfo.FadeSymbols > 0 && gainInfo.HoldEvents > 0, ...
    'One-tap gain tracker did not enter fade HOLD.');
assert(gainInfo.InverseGainMaxObserved_dB < 10, ...
    'Power-mode gain estimate still followed the fade/noise floor.');
assert(eqInfo.DDFadeHoldWindows > 0 && eqInfo.DDFadeEnterEvents > 0, ...
    'Common DD state machine did not enter fade HOLD.');
assert(eqInfo.DDFadeRecoverEvents > 0, ...
    'Common DD state machine did not recover after hysteresis.');

