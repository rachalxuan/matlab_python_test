% CODEX_FIRST_MODS_CONV_STREAM_PHASE_REGRESSION_V1
% Verify that continuous convolutional decoding selects phase hypotheses by
% decoded raw-ASM structure, without evaluator BER or transmitted bits.

common = struct( ...
    'CodeRates',"3/4", ...
    'TFBytes',1150, ...
    'WarmUpFrames',8, ...
    'MeasurementFrames',16, ...
    'DebugReceiver',false, ...
    'RunLegacyControl',false);

MainConvStreamHighRateOptions = common;
MainConvStreamHighRateOptions.ModTypes = "BPSK";
MainConvStreamHighRateOptions.PhaseOffset_deg = 180;
run(fullfile(fileparts(mfilename('fullpath')), ...
    'codex_main_conv_stream_high_rate_regression_v1.m'));
bpskRows = MainConvStreamHighRateResults;

MainConvStreamHighRateOptions = common;
MainConvStreamHighRateOptions.ModTypes = ["16QAM","32QAM"];
MainConvStreamHighRateOptions.PhaseOffset_deg = 90;
run(fullfile(fileparts(mfilename('fullpath')), ...
    'codex_main_conv_stream_high_rate_regression_v1.m'));
qamRows = MainConvStreamHighRateResults;

FirstModConvStreamPhaseResults = [bpskRows; qamRows];
disp(FirstModConvStreamPhaseResults(:,{ ...
    'ModType','CodeRate','SelectedRotation_deg','SelectedOffset', ...
    'LongestGoodASMRun','BER','FER','ComparedFrames', ...
    'CoverageStatus','Pass'}));
assert(all(FirstModConvStreamPhaseResults.Pass), ...
    'First-modulation phase-candidate regression failed.');
