% CODEX_FRONTEND_RS_VISUAL_SMOKE_V1
% Frontend-facing smoke test for the four ordinary modulations requested by
% the UI.  It uses the same run_ccsds_tm_evaluation entry point as server.py
% and requires three real PNG artifacts plus BER/frame-lock telemetry.

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);
addpath(fullfile(projectDir,'src','python'));

cases = [ ...
    struct('Mod',"QPSK", 'K',223,'I',2,'Rate',"3/4"); ...
    struct('Mod',"8PSK", 'K',239,'I',3,'Rate',"5/6"); ...
    struct('Mod',"16QAM",'K',223,'I',4,'Rate',"7/8"); ...
    struct('Mod',"32QAM",'K',239,'I',8,'Rate',"2/3")];

artifactRoot = fullfile(projectDir,'artifacts','ccsds', ...
    'frontend_visual_smoke');
if ~isfolder(artifactRoot), mkdir(artifactRoot); end

rows = repmat(struct('ModType',"",'RSProfile',"",'CodeRate',"", ...
    'BER',NaN,'FER',NaN,'ComparedFrames',NaN,'CoverageStatus',"", ...
    'CarrierLockAvailable',false,'TimingLockAvailable',false, ...
    'FrameLockAvailable',false,'ImageCount',0,'Pass',false), ...
    numel(cases),1);

fprintf('\n================ FRONTEND RS VISUAL SMOKE ================\n');
for iCase = 1:numel(cases)
    c = cases(iCase);
    outputDir = fullfile(artifactRoot,char(lower(c.Mod)));
    if ~isfolder(outputDir), mkdir(outputDir); end
    p = struct( ...
        'modType',char(c.Mod),'channelCoding','concatenated', ...
        'ConvolutionalCodeRate',char(c.Rate), ...
        'ConvolutionalReceiveMode','stream-raw-asm', ...
        'RSMessageLength',c.K,'RSInterleavingDepth',c.I, ...
        'IsRSMessageShortened',false, ...
        'NumBytesInTransferFrame',c.K*c.I, ...
        'symbolRate',10e6,'sps',8,'snr',100,'noiseMode','off', ...
        'noisePlacement','afterChannel','cfo',0,'phaseOffset',0, ...
        'delay',0,'RolloffFactor',0.35,'WaveformMode','ordinaryTM', ...
        'hasASM',true,'RandomizerEnabled',false, ...
        'RandomizerFECPosition','afterEncoding', ...
        'DataPathMode','single','TMDataSource','random', ...
        'PCMFormat','NRZ-L','berWarmUpFrames',4,'berFrames',4, ...
        'excludeBERWarmUpFrames',true,'enableHChannel',false, ...
        'HMode','none','normalizeHChannel',false, ...
        'enableEqualizer',false,'equalizerMode','off', ...
        'enableKnownHPreEqualizer',false, ...
        'normalizeEqualizerOutput',false,'enableConverterChain',false, ...
        'enableADCEquivalent',false,'inputLevelDbm',-10, ...
        'AGCEnabled',false,'showFigures',false, ...
        'showPipelineFigure',false,'showDamageBudgetFigure',false, ...
        'showPowerFigure',false,'enableRuntimeLockTelemetry',true, ...
        'enableReceiverTimeline',true,'runtimeStatusUpdateMs',200, ...
        'remoteMode',true,'includeRawData',false, ...
        'outputDir',outputDir,'seed',12000+iCase);

    fprintf('[%d/%d] %s + RS(255,%d), I=%d + conv %s\n', ...
        iCase,numel(cases),c.Mod,c.K,c.I,c.Rate);
    [m,imagePaths] = run_ccsds_tm_evaluation(p);
    paths = split(string(imagePaths),';');
    paths = paths(strlength(paths)>0);
    imagesExist = numel(paths)==3 && all(arrayfun( ...
        @(path)isfile(path) && dir(path).bytes>0,paths));
    coverage = m.MeasurementCoverage;
    locks = m.RuntimeLockTelemetry;
    coverageComplete = coverage.Available && coverage.Complete && ...
        coverage.ComparedFrames==4 && coverage.ExpectedFrames==4;
    metadataCorrect = strcmp(m.ConvolutionalReceiveMode, ...
        'stream-raw-asm') && m.RSMessageLength==c.K && ...
        m.RSInterleavingDepth==c.I;
    pass = m.success && m.BER==0 && m.FER==0 && ...
        coverageComplete && imagesExist && metadataCorrect && ...
        locks.Enabled && locks.Carrier.Available && ...
        locks.Timing.Available && locks.Frame.Available;

    rows(iCase) = struct('ModType',c.Mod, ...
        'RSProfile',sprintf('RS(255,%d), I=%d',c.K,c.I), ...
        'CodeRate',c.Rate,'BER',m.BER,'FER',m.FER, ...
        'ComparedFrames',coverage.ComparedFrames, ...
        'CoverageStatus',string(coverage.Status), ...
        'CarrierLockAvailable',logical(locks.Carrier.Available), ...
        'TimingLockAvailable',logical(locks.Timing.Available), ...
        'FrameLockAvailable',logical(locks.Frame.Available), ...
        'ImageCount',numel(paths),'Pass',logical(pass));
end

FrontendRSVisualSmokeResults = struct2table(rows);
disp(FrontendRSVisualSmokeResults);
assert(all(FrontendRSVisualSmokeResults.Pass), ...
    'At least one frontend RS visual smoke case failed.');
fprintf('PASS: 4/4 frontend modulation cases produced audited metrics and three real images.\n');
fprintf('Images: %s\n',artifactRoot);
