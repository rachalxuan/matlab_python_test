% CODEX_FULL_RS_CONV_STREAM_MATRIX_V1
% Exhaustive non-shortened outer-RS / continuous inner-convolutional test.
%
% QPSK matrix:
%   RS(255,223), RS(255,239)
%   interleaving depth 1, 2, 3, 4, 5, 8
%   inner convolutional rate 1/2, 2/3, 3/4, 5/6, 7/8
%
% Noiseless pass criteria deliberately inspect both sides of the outer RS
% decoder: the raw RS codeword must already be bit-exact, the decoded TM
% transfer frame must be bit-exact, and measurement coverage must be full.
% Shortened RS profiles are intentionally outside this regression.

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);
addpath(fullfile(projectDir,'src','python'));

if ~exist('FullRSConvStreamOptions','var') || ...
        ~isstruct(FullRSConvStreamOptions)
    FullRSConvStreamOptions = struct;
end

rsMessageLengths = localVector(FullRSConvStreamOptions, ...
    'RSMessageLengths',[223 239]);
interleavingDepths = localVector(FullRSConvStreamOptions, ...
    'InterleavingDepths',[1 2 3 4 5 8]);
codeRates = string(localField(FullRSConvStreamOptions, ...
    'CodeRates',["1/2","2/3","3/4","5/6","7/8"]));
warmupFrames = localNumber(FullRSConvStreamOptions,'WarmUpFrames',8);
measurementFrames = localNumber(FullRSConvStreamOptions, ...
    'MeasurementFrames',120);
debugReceiver = localLogical(FullRSConvStreamOptions, ...
    'DebugReceiver',false);
baseSeed = localNumber(FullRSConvStreamOptions,'BaseSeed',9000);
runModulationSpotChecks = localLogical(FullRSConvStreamOptions, ...
    'RunModulationSpotChecks',true);

numMatrixCases = numel(rsMessageLengths)*numel(interleavingDepths)* ...
    numel(codeRates);
matrixRows = repmat(localEmptyRow(),numMatrixCases,1);
caseIndex = 0;

fprintf('\n================ FULL RS + CONTINUOUS CONV QPSK MATRIX ================\n');
for rsK = rsMessageLengths(:).'
    for rsI = interleavingDepths(:).'
        for rate = codeRates(:).'
            caseIndex = caseIndex + 1;
            name = sprintf('QPSK RS%d I=%d + conv %s', ...
                rsK,rsI,char(rate));
            fprintf('\n[%d/%d] %s\n',caseIndex,numMatrixCases,name);
            matrixRows(caseIndex) = localRunCase(name,"QPSK", ...
                rsK,rsI,rate,warmupFrames,measurementFrames, ...
                debugReceiver,baseSeed+caseIndex);
            localPrint(matrixRows(caseIndex));
        end
    end
end

FullRSConvStreamResults = struct2table(matrixRows);
disp(FullRSConvStreamResults(:,{ ...
    'ModType','RSMessageLength','RSInterleavingDepth','CodeRate', ...
    'RawFrameRemainder','RawCodewordBitErrors', ...
    'RawCodewordErrorFrames','RSCorrectedSymbols','BER','FER', ...
    'ComparedFrames','ExpectedFrames','CoverageStatus','Pass'}));

assert(all(FullRSConvStreamResults.Pass), ...
    'At least one full-RS QPSK matrix case failed.');
fprintf('PASS: %d/%d full-RS QPSK matrix cases passed.\n', ...
    nnz(FullRSConvStreamResults.Pass),height(FullRSConvStreamResults));

spotRows = repmat(localEmptyRow(),0,1);
if runModulationSpotChecks
    spotCases = [ ...
        struct('Name',"BPSK RS223 I=2 + conv 3/4", ...
            'Mod',"BPSK",'K',223,'I',2,'Rate',"3/4"); ...
        struct('Name',"8PSK RS239 I=3 + conv 5/6", ...
            'Mod',"8PSK",'K',239,'I',3,'Rate',"5/6"); ...
        struct('Name',"16QAM RS223 I=5 + conv 7/8", ...
            'Mod',"16QAM",'K',223,'I',5,'Rate',"7/8"); ...
        struct('Name',"32QAM RS239 I=8 + conv 2/3", ...
            'Mod',"32QAM",'K',239,'I',8,'Rate',"2/3")];
    spotRows = repmat(localEmptyRow(),numel(spotCases),1);
    fprintf('\n================ FULL RS ORDINARY-MODULATION SPOT CHECKS ================\n');
    for iCase = 1:numel(spotCases)
        c = spotCases(iCase);
        fprintf('\n[%d/%d] %s\n',iCase,numel(spotCases),c.Name);
        spotRows(iCase) = localRunCase(c.Name,c.Mod,c.K,c.I,c.Rate, ...
            warmupFrames,measurementFrames,debugReceiver,9800+iCase);
        localPrint(spotRows(iCase));
    end
    FullRSOrdinaryModSpotCheckResults = struct2table(spotRows);
    disp(FullRSOrdinaryModSpotCheckResults(:,{ ...
        'ModType','RSMessageLength','RSInterleavingDepth','CodeRate', ...
        'RawFrameRemainder','RawCodewordBitErrors', ...
        'RSCorrectedSymbols','BER','FER','ComparedFrames', ...
        'CoverageStatus','Pass'}));
    assert(all(FullRSOrdinaryModSpotCheckResults.Pass), ...
        'At least one ordinary-modulation full-RS spot check failed.');
    fprintf('PASS: %d/%d ordinary-modulation full-RS spot checks passed.\n', ...
        nnz(FullRSOrdinaryModSpotCheckResults.Pass), ...
        height(FullRSOrdinaryModSpotCheckResults));
else
    FullRSOrdinaryModSpotCheckResults = struct2table(spotRows);
end

function row = localRunCase(name,modType,rsK,rsI,rate, ...
        warmupFrames,measurementFrames,debugReceiver,seed)
    tfBytes = rsK*rsI;
    rawFrameBits = 32 + 255*rsI*8;
    puncture = ccsdsTMConvolutionalPunctureConfig(rate);
    remainder = mod(rawFrameBits,puncture.InputBitsPerPeriod);
    p = struct( ...
        'modType',char(modType),'channelCoding','concatenated', ...
        'ConvolutionalCodeRate',char(rate), ...
        'ConvolutionalReceiveMode','stream-raw-asm', ...
        'RSMessageLength',rsK,'RSInterleavingDepth',rsI, ...
        'IsRSMessageShortened',false, ...
        'symbolRate',10e6,'sps',8,'snr',100,'noiseMode','off', ...
        'noisePlacement','afterChannel','cfo',0,'phaseOffset',0, ...
        'delay',0,'RolloffFactor',0.35,'WaveformMode','ordinaryTM', ...
        'NumBytesInTransferFrame',tfBytes,'hasASM',true, ...
        'RandomizerEnabled',false,'RandomizerFECPosition','afterEncoding', ...
        'DataPathMode','single','TMDataSource','random','PCMFormat','NRZ-L', ...
        'berWarmUpFrames',warmupFrames,'berFrames',measurementFrames, ...
        'excludeBERWarmUpFrames',true,'enableHChannel',false, ...
        'HMode','none','normalizeHChannel',false, ...
        'enableEqualizer',false,'equalizerMode','off', ...
        'enableKnownHPreEqualizer',false, ...
        'normalizeEqualizerOutput',false,'enableConverterChain',false, ...
        'enableADCEquivalent',false,'inputLevelDbm',-10, ...
        'AGCEnabled',false,'showFigures',false, ...
        'showPipelineFigure',false,'showDamageBudgetFigure',false, ...
        'showPowerFigure',false, ...
        'debugContinuousConvReceiver',debugReceiver, ...
        'debugCodedBoundary',false,'debugPerFrameBERSummary',false, ...
        'seed',seed);
    m = run_ccsds_tm_evaluation(p);

    coverageComplete = isfield(m,'MeasurementCoverage') && ...
        strcmpi(string(m.MeasurementCoverage.Status),'COMPLETE') && ...
        m.MeasurementCoverage.ComparedFrames == measurementFrames && ...
        m.MeasurementCoverage.ExpectedFrames == measurementFrames && ...
        m.MeasurementCoverage.UnrecoveredFrames == 0 && ...
        m.MeasurementCoverage.RecoveredNotComparedFrames == 0;
    rawBitErrors = localField(m, ...
        'ContinuousConvOuterRSMeasurementRawCodewordBitErrors',NaN);
    rawErrorFrames = localField(m, ...
        'ContinuousConvOuterRSMeasurementRawCodewordErrorFrames',NaN);
    rawFrameErrors = double(localField(m, ...
        'ContinuousConvOuterRSRawCodewordFrameBitErrors',zeros(0,1)));
    correctedSymbols = localField(m, ...
        'ContinuousConvOuterRSMeasurementCorrectedSymbols',NaN);
    rawMappedFrames = localField(m, ...
        'ContinuousConvOuterRSMeasurementMappedFrames',NaN);
    uncorrectableFrames = localField(m, ...
        'ContinuousConvOuterRSMeasurementUncorrectableFrames',NaN);
    pass = logical(m.success) && m.BER == 0 && m.FER == 0 && ...
        coverageComplete && ...
        logical(localField(m,'ContinuousConvReceiverAvailable',false)) && ...
        localField(m,'ContinuousConvLongestGoodASMRun',0) >= 4 && ...
        logical(localField(m,'ContinuousConvOuterRSDecodeApplied',false)) && ...
        uncorrectableFrames == 0 && correctedSymbols == 0 && ...
        rawBitErrors == 0 && rawErrorFrames == 0 && ...
        rawMappedFrames == measurementFrames;

    row = struct('CaseName',string(name),'ModType',string(modType), ...
        'RSMessageLength',rsK,'RSInterleavingDepth',rsI, ...
        'CodeRate',string(rate),'TFBytes',tfBytes, ...
        'RawFrameBits',rawFrameBits,'RawFrameRemainder',remainder, ...
        'ReceiverAvailable',logical(localField(m, ...
            'ContinuousConvReceiverAvailable',false)), ...
        'SelectedOffset',localField(m,'ContinuousConvSelectedOffset',NaN), ...
        'LongestGoodASMRun',localField(m, ...
            'ContinuousConvLongestGoodASMRun',NaN), ...
        'RecoveredFrames',localField(m, ...
            'ContinuousConvRecoveredFrames',NaN), ...
        'RawCodewordBits',localField(m, ...
            'ContinuousConvOuterRSMeasurementRawCodewordBits',NaN), ...
        'RawCodewordBitErrors',rawBitErrors, ...
        'RawCodewordErrorFrames',rawErrorFrames, ...
        'RawCodewordFrameErrorPattern',string(mat2str(rawFrameErrors(:).')), ...
        'RawCodewordMappedFrames',rawMappedFrames, ...
        'AllRawCodewordBitErrors',localField(m, ...
            'ContinuousConvOuterRSRawCodewordBitErrors',NaN), ...
        'AllRawCodewordErrorFrames',localField(m, ...
            'ContinuousConvOuterRSRawCodewordErrorFrames',NaN), ...
        'RSCorrectedSymbols',correctedSymbols, ...
        'RSUncorrectableFrames',uncorrectableFrames, ...
        'BER',m.BER,'FER',m.FER, ...
        'ComparedFrames',m.MeasurementCoverage.ComparedFrames, ...
        'ExpectedFrames',m.MeasurementCoverage.ExpectedFrames, ...
        'CoverageStatus',string(m.MeasurementCoverage.Status), ...
        'Pass',logical(pass));
end

function localPrint(row)
    fprintf(['  raw=%d bits, puncture remainder=%d, offset=%g, ', ...
        'ASM run=%g, recovered=%g\n'],row.RawFrameBits, ...
        row.RawFrameRemainder,row.SelectedOffset,row.LongestGoodASMRun, ...
        row.RecoveredFrames);
    fprintf(['  measurement pre-RS errors=%g/%g bits in %g frames, ', ...
        'corrected=%g symbols, ', ...
        'uncorrectable=%g\n'],row.RawCodewordBitErrors, ...
        row.RawCodewordBits,row.RawCodewordErrorFrames, ...
        row.RSCorrectedSymbols,row.RSUncorrectableFrames);
    if row.AllRawCodewordErrorFrames > 0
        fprintf(['  all decoder output (including guard tail): ', ...
            'errors=%g bits in %g frames, pattern=%s\n'], ...
            row.AllRawCodewordBitErrors,row.AllRawCodewordErrorFrames, ...
            row.RawCodewordFrameErrorPattern);
    end
    fprintf('  post-RS BER=%g FER=%g, coverage=%g/%g (%s) -> %s\n', ...
        row.BER,row.FER,row.ComparedFrames,row.ExpectedFrames, ...
        row.CoverageStatus,localPassLabel(row.Pass));
end

function value = localField(s,name,defaultValue)
    value = defaultValue;
    if isfield(s,name) && ~isempty(s.(name))
        value = s.(name);
    end
end

function value = localNumber(s,name,defaultValue)
    value = double(localField(s,name,defaultValue));
end

function value = localLogical(s,name,defaultValue)
    value = logical(localField(s,name,defaultValue));
end

function value = localVector(s,name,defaultValue)
    value = double(localField(s,name,defaultValue));
end

function label = localPassLabel(pass)
    if pass
        label = 'PASS';
    else
        label = 'FAIL';
    end
end

function row = localEmptyRow()
    row = struct('CaseName',"",'ModType',"", ...
        'RSMessageLength',NaN,'RSInterleavingDepth',NaN, ...
        'CodeRate',"",'TFBytes',NaN,'RawFrameBits',NaN, ...
        'RawFrameRemainder',NaN,'ReceiverAvailable',false, ...
        'SelectedOffset',NaN,'LongestGoodASMRun',NaN, ...
        'RecoveredFrames',NaN,'RawCodewordBits',NaN, ...
        'RawCodewordBitErrors',NaN,'RawCodewordErrorFrames',NaN, ...
        'RawCodewordFrameErrorPattern',"", ...
        'RawCodewordMappedFrames',NaN,'AllRawCodewordBitErrors',NaN, ...
        'AllRawCodewordErrorFrames',NaN, ...
        'RSCorrectedSymbols',NaN,'RSUncorrectableFrames',NaN, ...
        'BER',NaN,'FER',NaN,'ComparedFrames',NaN, ...
        'ExpectedFrames',NaN,'CoverageStatus',"",'Pass',false);
end
