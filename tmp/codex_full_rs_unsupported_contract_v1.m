% CODEX_FULL_RS_UNSUPPORTED_CONTRACT_V1
% Negative contract: this phase must not silently claim shortened RS or
% device-only interleaving depths I=6/7.

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);
addpath(fullfile(projectDir,'src','python'));

base = struct( ...
    'modType','QPSK','channelCoding','concatenated', ...
    'ConvolutionalCodeRate','3/4', ...
    'ConvolutionalReceiveMode','stream-raw-asm', ...
    'RSMessageLength',223,'RSInterleavingDepth',1, ...
    'IsRSMessageShortened',false, ...
    'NumBytesInTransferFrame',223, ...
    'symbolRate',10e6,'sps',8,'snr',100,'noiseMode','off', ...
    'cfo',0,'phaseOffset',0,'delay',0,'hasASM',true, ...
    'RandomizerEnabled',false,'DataPathMode','single', ...
    'PCMFormat','NRZ-L','berWarmUpFrames',2,'berFrames',2, ...
    'showFigures',false,'showPipelineFigure',false);

cases = [ ...
    struct('Name',"interleaving depth 6",'I',6,'Shortened',false,'S',223); ...
    struct('Name',"interleaving depth 7",'I',7,'Shortened',false,'S',223); ...
    struct('Name',"shortened RS",'I',1,'Shortened',true,'S',200)];

for k = 1:numel(cases)
    p = base;
    p.RSInterleavingDepth = cases(k).I;
    p.IsRSMessageShortened = cases(k).Shortened;
    p.RSShortenedMessageLength = cases(k).S;
    p.NumBytesInTransferFrame = cases(k).S*cases(k).I;
    try
        result = run_ccsds_tm_evaluation(p);
        rejected = isstruct(result) && isfield(result,'success') && ...
            ~logical(result.success) && isfield(result,'errorIdentifier') && ...
            strcmp(string(result.errorIdentifier), ...
            "run_ccsds_tm_evaluation:ContinuousConvUnsupportedProfile");
    catch err
        rejected = strcmp(err.identifier, ...
            'run_ccsds_tm_evaluation:ContinuousConvUnsupportedProfile');
        if ~rejected
            rethrow(err);
        end
    end
    assert(rejected,'Unsupported profile was silently accepted: %s', ...
        cases(k).Name);
    fprintf('PASS: rejected %s.\n',cases(k).Name);
end

fprintf('PASS: shortened RS and I=6/7 remain explicitly unsupported.\n');
