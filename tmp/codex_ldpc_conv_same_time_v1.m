function [T,logs,results]=codex_ldpc_conv_same_time_v1(warmupBlocks,measurementBlocks,channelFile)
% 8PSK LDPC/conv 1/2: identical channel-time measurement interval.
% Default: 8.753067--17.506133 ms. (7,2): 61.271467--78.777600 ms.
% No files are written. Same H/time/receiver/seed, NOT identical coded data
% or information throughput. This is not an Eb/N0 coding-gain experiment.
root=fileparts(fileparts(mfilename('fullpath')));
addpath(fullfile(root,'src','python'));
if nargin<1, warmupBlocks=1; end
if nargin<2, measurementBlocks=1; end
if nargin<3
    % Explicit current channel catalogue location (no old ChannelData_7).
    channelFile=fullfile('C:/Users/admin/xwechat_files', ...
        'wxid_95czmz1vt20422_de63/msg/file/2026-09','mat文件','mat文件', ...
        '3GPPNTN-CDL_A_4_AntennaGain_1.mat');
end
validateattributes(warmupBlocks,{'numeric'},{'scalar','integer','nonnegative'});
validateattributes(measurementBlocks,{'numeric'},{'scalar','integer','positive'});
assert(isfile(channelFile),'Channel file not found: %s',channelFile);

% LDPC: 64-bit ASM + 2048 code bits, K=1024.
% Conv: rate 1/2 applied to 32-bit ASM + 1115-byte transfer frame.
codedBitsPerFrame=[64+2048,2*(32+1115*8)];
commonBits=lcm(codedBitsPerFrame(1),codedBitsPerFrame(2));
framesPerBlock=commonBits./codedBitsPerFrame;
symbolRate=30e6; bitsPerSymbol=3;
blockSeconds=commonBits/bitsPerSymbol/symbolRate;
startTime=warmupBlocks*blockSeconds;
endTime=(warmupBlocks+measurementBlocks)*blockSeconds;
fprintf('Common measurement interval: %.6f--%.6f ms (8PSK, 30 Msym/s, noise OFF)\n', ...
    1e3*startTime,1e3*endTime);
fprintf('One common block: LDPC %d frames / conv %d frames / %.6f ms\n', ...
    framesPerBlock(1),framesPerBlock(2),1e3*blockSeconds);
fprintf('Filter/decoder flush guards are excluded; total buffered durations may differ.\n');
fprintf('H is normalized per waveform. Noiseless normalized-H comparison, not an absolute link budget.\n');

p=struct('modType','8PSK','symbolRate',symbolRate,'sps',8, ...
    'RolloffFactor',0.35,'snr',100,'noiseMode','off','noisePlacement','afterChannel', ...
    'cfo',0,'phaseOffset',0,'delay',0,'inputLevelDbm',-10, ...
    'WaveformMode','ordinaryTM','NumBytesInTransferFrame',1115, ...
    'hasASM',true,'RandomizerEnabled',false,'RandomizerFECPosition','afterEncoding', ...
    'DataPathMode','single','TMDataSource','random','PCMFormat','NRZ-L', ...
    'excludeBERWarmUpFrames',true, ...
    'enableHChannel',true,'HMode','h_matrix_file','channelFilePath',char(channelFile), ...
    'channelPathPowerMode','embedded','channelSampleRateHz',1e5, ...
    'channelInterpolationMethod','linear','channelOutOfRangeMode','hold', ...
    'interpolateChannelDelays',true,'normalizeHChannel',true, ...
    'enableEqualizer',true,'equalizerMode','blind-cma-lms', ...
    'normalizeEqualizerOutput',true,'enableKnownHPreEqualizer',false, ...
    'adaptiveEqualizerSamplingMode','2sps-dual', ...
    'adaptiveFractionalEqualizerTaps',129,'adaptiveFractionalEqualizerStep',2e-4, ...
    'adaptiveFractionalEqualizerWeightUpdatePeriod',1,'adaptiveFractionalPostMode','off', ...
    'PSKPostFSEPhaseTrackerMode','off','enableBlindReliabilityManager',false, ...
    'enablePSKCoarseFrequencyCompensator',true,'carrierCaptureRangeHz',2e6, ...
    'carrierLoopBandwidth',0.0025,'timingLoopBandwidth',0.01, ...
    'enableASMFramePhaseCorrection',true,'enableConverterChain',false, ...
    'enableADCEquivalent',false,'AGCEnabled',false, ...
    'enableRuntimeLockTelemetry',true,'runtimeStatusUpdateMs',200, ...
    'collectPredecoderStats',true,'showFigures',false,'showPipelineFigure',false, ...
    'showDamageBudgetFigure',false,'showPowerFigure',false, ...
    'debugCodedBoundary',false,'debugAdaptiveEqualizer',false,'debugASMPhase',false);
codes=["LDPC","convolutional"];
rows=cell(2,1); logs=cell(2,1); results=cell(2,1);
for k=1:2
    q=p; q.channelCoding=char(codes(k));
    q.berWarmUpFrames=warmupBlocks*framesPerBlock(k);
    q.berFrames=measurementBlocks*framesPerBlock(k);
    if k==1
        q.CodeRate='1/2'; q.NumBitsInInformationBlock=1024; q.IsLDPCOnSMTF=false;
    else
        q.ConvolutionalCodeRate='1/2';
    end
    fprintf('[%d/2] %s: warmup=%d, measurement=%d frames ...\n', ...
        k,codes(k),q.berWarmUpFrames,q.berFrames);
    rng(364232726,'twister');
    timer=tic;
    logs{k}=evalc('[r,~]=run_ccsds_tm_evaluation(q);');
    elapsed=toc(timer); results{k}=r;
    assert(r.success,'Receiver run failed; inspect logs{%d}.',k);
    L=r.ReceiverTimeline;
    assert(L.Available,'Missing measurement timeline: %s',L.Reason);
    timeline=struct2table(L.Rows); measured=timeline.MeasurementEligible;
    actualStart=min(timeline.TimeStart_s(measured));
    actualEnd=max(timeline.TimeEnd_s(measured));
    assert(abs(actualStart-startTime)<1e-10 && abs(actualEnd-endTime)<1e-10, ...
        'Actual frame-time interval differs from the requested common interval.');
    coverage=r.MeasurementCoverage;
    errors=sum(timeline.ErrorBitsDelta(measured));
    compared=sum(timeline.ComparedBitsDelta(measured));
    verdict=string(coverage.Status);
    if coverage.Complete
        if r.BER==0 && r.FER==0, verdict="PASS"; else, verdict="DECODE_ERRORS"; end
    end
    rows{k}=table(codes(k),q.berWarmUpFrames,q.berFrames, ...
        1e3*actualStart,1e3*actualEnd,r.PredecoderSteadyBER,r.PredecoderASMAligned, ...
        r.DemodNoiseVariance,r.BER,r.FER,errors,compared, ...
        coverage.ComparedFrames,coverage.ExpectedFrames,verdict,elapsed, ...
        'VariableNames',{'Coding','WarmupFrames','MeasurementFrames', ...
        'MeasurementStart_ms','MeasurementEnd_ms','PredecoderBER','ASMAligned', ...
        'DemodNoiseVariance','BER','FER','ErrorBits','ComparedBits', ...
        'ComparedFrames','ExpectedFrames','Verdict','Elapsed_s'});
    fprintf('  BER=%g FER=%g preBER=%g coverage=%d/%d (%s), %.2f s\n', ...
        r.BER,r.FER,r.PredecoderSteadyBER,coverage.ComparedFrames, ...
        coverage.ExpectedFrames,verdict,elapsed);
end
T=vertcat(rows{:});
disp(T);
fprintf('Rows include every eligible physical frame; missing coverage is NOT a zero BER.\n');
fprintf('A zero-error finite run does not establish a universal BER < 1e-6 guarantee.\n');
end
