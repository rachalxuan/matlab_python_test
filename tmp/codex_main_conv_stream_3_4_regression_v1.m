% CODEX_MAIN_CONV_STREAM_3_4_REGRESSION_V1
% Main-path regression for the opt-in continuous punctured-convolutional RX.
% The production default remains legacy-coded-asm.  This experiment only
% enables stream-raw-asm for QPSK + convolutional 3/4 + NRZ-L + single path.

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);
addpath(fullfile(projectDir,'src','python'));

if ~exist('MainConvStream34Options','var') || ...
        ~isstruct(MainConvStream34Options)
    MainConvStream34Options = struct;
end
tfBytesList = localVector(MainConvStream34Options, ...
    'TFBytesList',[1149 1150 1151]);
warmupFrames = localNumber(MainConvStream34Options,'WarmUpFrames',8);
measurementFrames = localNumber(MainConvStream34Options, ...
    'MeasurementFrames',16);
debugReceiver = localLogical(MainConvStream34Options, ...
    'DebugReceiver',false);
runLegacyControl = localLogical(MainConvStream34Options, ...
    'RunLegacyControl',true);
phaseOffsetDeg = localNumber(MainConvStream34Options, ...
    'PhaseOffsetDeg',0);

rows = repmat(localEmptyRow(),numel(tfBytesList)+double(runLegacyControl),1);
fprintf('\n================ MAIN QPSK CONV 3/4 STREAM REGRESSION ================\n');
for iCase = 1:numel(tfBytesList)
    tfBytes = tfBytesList(iCase);
    p = localBaseOptions(tfBytes,warmupFrames,measurementFrames);
    p.phaseOffset = phaseOffsetDeg;
    p.ConvolutionalReceiveMode = 'stream-raw-asm';
    p.debugContinuousConvReceiver = debugReceiver;
    fprintf('\n[stream %d/%d] TF=%d Byte, raw (ASM+TF) mod 3 = %d\n', ...
        iCase,numel(tfBytesList),tfBytes,mod(32+8*tfBytes,3));
    m = run_ccsds_tm_evaluation(p);
    rows(iCase) = localResultRow('stream-raw-asm',tfBytes,m, ...
        measurementFrames);
    fprintf(['  success=%d available=%d drop=%g run=%g recovered=%g ', ...
        'BER=%.4g FER=%.4g coverage=%g/%g -> %s\n'], ...
        m.success,localField(m,'ContinuousConvReceiverAvailable',false), ...
        localField(m,'ContinuousConvSelectedOffset',NaN), ...
        localField(m,'ContinuousConvLongestGoodASMRun',NaN), ...
        localField(m,'ContinuousConvRecoveredFrames',NaN), ...
        m.BER,m.FER,m.MeasurementCoverage.ComparedFrames, ...
        m.MeasurementCoverage.ExpectedFrames,localPassLabel(rows(iCase).Pass));
end

if runLegacyControl
    % One aligned legacy control proves that the new mode did not replace or
    % silently alter the existing default receiver.
    legacyTFBytes = 1151;
    p = localBaseOptions(legacyTFBytes,warmupFrames,measurementFrames);
    p.phaseOffset = phaseOffsetDeg;
    p.ConvolutionalReceiveMode = 'legacy-coded-asm';
    fprintf('\n[legacy control] TF=%d Byte, raw (ASM+TF) mod 3 = %d\n', ...
        legacyTFBytes,mod(32+8*legacyTFBytes,3));
    m = run_ccsds_tm_evaluation(p);
    rows(end) = localResultRow('legacy-coded-asm',legacyTFBytes,m, ...
        measurementFrames);
    fprintf('  success=%d BER=%.4g FER=%.4g coverage=%g/%g -> %s\n', ...
        m.success,m.BER,m.FER,m.MeasurementCoverage.ComparedFrames, ...
        m.MeasurementCoverage.ExpectedFrames,localPassLabel(rows(end).Pass));
end

MainConvStream34Results = struct2table(rows);
disp(MainConvStream34Results);
assert(all(MainConvStream34Results.Pass), ...
    'Main-path continuous 3/4 regression failed. Inspect MainConvStream34Results.');
fprintf('PASS: %d/%d main-path cases passed.\n', ...
    nnz(MainConvStream34Results.Pass),height(MainConvStream34Results));

function p = localBaseOptions(tfBytes,warmupFrames,measurementFrames)
    p = struct( ...
        'modType','QPSK', ...
        'channelCoding','convolutional', ...
        'ConvolutionalCodeRate','3/4', ...
        'symbolRate',10e6, ...
        'sps',8, ...
        'snr',100, ...
        'noiseMode','off', ...
        'noisePlacement','afterChannel', ...
        'cfo',0, ...
        'phaseOffset',0, ...
        'delay',0, ...
        'RolloffFactor',0.35, ...
        'WaveformMode','ordinaryTM', ...
        'NumBytesInTransferFrame',tfBytes, ...
        'hasASM',true, ...
        'RandomizerEnabled',false, ...
        'RandomizerFECPosition','afterEncoding', ...
        'DataPathMode','single', ...
        'TMDataSource','random', ...
        'PCMFormat','NRZ-L', ...
        'berWarmUpFrames',warmupFrames, ...
        'berFrames',measurementFrames, ...
        'excludeBERWarmUpFrames',true, ...
        'enableHChannel',false, ...
        'HMode','none', ...
        'normalizeHChannel',false, ...
        'enableEqualizer',false, ...
        'equalizerMode','off', ...
        'enableKnownHPreEqualizer',false, ...
        'normalizeEqualizerOutput',false, ...
        'enableConverterChain',false, ...
        'enableADCEquivalent',false, ...
        'inputLevelDbm',-10, ...
        'AGCEnabled',false, ...
        'showFigures',false, ...
        'showPipelineFigure',false, ...
        'showDamageBudgetFigure',false, ...
        'showPowerFigure',false, ...
        'debugCodedBoundary',false, ...
        'debugPerFrameBERSummary',false, ...
        'seed',7341);
end

function row = localResultRow(mode,tfBytes,m,measurementFrames)
    available = localField(m,'ContinuousConvReceiverAvailable',NaN);
    streamMode = strcmp(mode,'stream-raw-asm');
    coverageComplete = isfield(m,'MeasurementCoverage') && ...
        strcmpi(string(m.MeasurementCoverage.Status),'COMPLETE') && ...
        m.MeasurementCoverage.ComparedFrames == measurementFrames;
    pass = logical(m.success) && m.BER == 0 && m.FER == 0 && ...
        coverageComplete;
    if streamMode
        pass = pass && logical(available) && ...
            localField(m,'ContinuousConvLongestGoodASMRun',0) >= 4;
    end
    row = struct( ...
        'Mode',string(mode), ...
        'TFBytes',tfBytes, ...
        'RawFrameRemainderMod3',mod(32+8*tfBytes,3), ...
        'Success',logical(m.success), ...
        'ReceiverAvailable',available, ...
        'SelectedOffset',localField(m, ...
            'ContinuousConvSelectedOffset',NaN), ...
        'LongestGoodASMRun',localField(m, ...
            'ContinuousConvLongestGoodASMRun',NaN), ...
        'RecoveredFrames',localField(m, ...
            'ContinuousConvRecoveredFrames',NaN), ...
        'BER',m.BER, ...
        'FER',m.FER, ...
        'ComparedFrames',m.MeasurementCoverage.ComparedFrames, ...
        'ExpectedFrames',m.MeasurementCoverage.ExpectedFrames, ...
        'CoverageStatus',string(m.MeasurementCoverage.Status), ...
        'Pass',logical(pass));
end

function value = localField(s,name,defaultValue)
    if isfield(s,name) && ~isempty(s.(name))
        value = s.(name);
    else
        value = defaultValue;
    end
end

function value = localNumber(s,name,defaultValue)
    value = double(localField(s,name,defaultValue));
end

function value = localLogical(s,name,defaultValue)
    value = logical(localField(s,name,defaultValue));
end

function value = localVector(s,name,defaultValue)
    value = double(localField(s,name,defaultValue));
    value = reshape(value,1,[]);
end

function label = localPassLabel(pass)
    if pass
        label = 'PASS';
    else
        label = 'FAIL';
    end
end

function row = localEmptyRow()
    row = struct( ...
        'Mode',"", ...
        'TFBytes',NaN, ...
        'RawFrameRemainderMod3',NaN, ...
        'Success',false, ...
        'ReceiverAvailable',NaN, ...
        'SelectedOffset',NaN, ...
        'LongestGoodASMRun',NaN, ...
        'RecoveredFrames',NaN, ...
        'BER',NaN, ...
        'FER',NaN, ...
        'ComparedFrames',NaN, ...
        'ExpectedFrames',NaN, ...
        'CoverageStatus',"", ...
        'Pass',false);
end
