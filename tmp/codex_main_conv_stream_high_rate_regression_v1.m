% CODEX_MAIN_CONV_STREAM_HIGH_RATE_REGRESSION_V1
% Actual TM generator + waveform + ordinary receiver regression. CodeRates
% selects any supported continuous convolutional rate. Legacy controls remain
% aligned and prove that the opt-in did not change the default path.

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);
addpath(fullfile(projectDir,'src','python'));

if ~exist('MainConvStreamHighRateOptions','var') || ...
        ~isstruct(MainConvStreamHighRateOptions)
    MainConvStreamHighRateOptions = struct;
end
warmupFrames = localNumber(MainConvStreamHighRateOptions,'WarmUpFrames',8);
measurementFrames = localNumber(MainConvStreamHighRateOptions, ...
    'MeasurementFrames',120);
debugReceiver = localLogical(MainConvStreamHighRateOptions, ...
    'DebugReceiver',true);
runLegacyControl = localLogical(MainConvStreamHighRateOptions, ...
    'RunLegacyControl',true);
rates = string(localField(MainConvStreamHighRateOptions,'CodeRates', ...
    ["5/6","7/8"]));
modTypes = string(localField(MainConvStreamHighRateOptions,'ModTypes', ...
    "QPSK"));
tfList = double(localField(MainConvStreamHighRateOptions,'TFBytes', ...
    [1150 1151]));
phaseOffset = localNumber(MainConvStreamHighRateOptions, ...
    'PhaseOffset_deg',0);
rowsPerRate = numel(tfList)+double(runLegacyControl);
rows = repmat(localEmptyRow(),numel(modTypes)*numel(rates)*rowsPerRate,1);
rowIndex = 0;

fprintf('\n================ MAIN CONTINUOUS-CONV STREAM REGRESSION ================\n');
for modType = modTypes
    for rate = rates
        cfg = ccsdsTMConvolutionalPunctureConfig(rate);
        for tfBytes = tfList
            p = localBaseOptions(modType,tfBytes,warmupFrames, ...
                measurementFrames,phaseOffset);
            p.ConvolutionalCodeRate = char(rate);
            p.ConvolutionalReceiveMode = 'stream-raw-asm';
            p.debugContinuousConvReceiver = debugReceiver;
            fprintf(['\n[stream] mod=%s rate=%s TF=%d B, ', ...
                'phase=%+.1f deg, raw remainder=%d/%d\n'], ...
                modType,rate,tfBytes,phaseOffset, ...
                mod(32+8*tfBytes,cfg.InputBitsPerPeriod), ...
                cfg.InputBitsPerPeriod);
            m = run_ccsds_tm_evaluation(p);
            rowIndex = rowIndex+1;
            rows(rowIndex) = localResultRow('stream-raw-asm',modType, ...
                rate,tfBytes,cfg.InputBitsPerPeriod,m, ...
                measurementFrames); %#ok<SAGROW>
            localPrint(rows(rowIndex));
        end
        if runLegacyControl
            tfBytes = 1151;
            p = localBaseOptions(modType,tfBytes,warmupFrames, ...
                measurementFrames,phaseOffset);
            p.ConvolutionalCodeRate = char(rate);
            p.ConvolutionalReceiveMode = 'legacy-coded-asm';
            fprintf(['\n[legacy aligned control] mod=%s rate=%s ', ...
                'TF=%d B, phase=%+.1f deg\n'], ...
                modType,rate,tfBytes,phaseOffset);
            m = run_ccsds_tm_evaluation(p);
            rowIndex = rowIndex+1;
            rows(rowIndex) = localResultRow('legacy-coded-asm',modType, ...
                rate,tfBytes,cfg.InputBitsPerPeriod,m, ...
                measurementFrames); %#ok<SAGROW>
            localPrint(rows(rowIndex));
        end
    end
end

MainConvStreamHighRateResults = struct2table(rows);
disp(MainConvStreamHighRateResults);
assert(all(MainConvStreamHighRateResults.Pass), ...
    'Main high-rate stream regression failed.');
fprintf('PASS: %d/%d actual main-path cases passed.\n', ...
    nnz(MainConvStreamHighRateResults.Pass), ...
    height(MainConvStreamHighRateResults));

% Safety regression: opting out of stream-raw-asm must retain the original
% guard.  This prevents a legacy coded-ASM receiver from silently accepting
% a frame whose puncture phase changes at the next ASM.
guardRates = intersect(rates,["5/6","7/8"],'stable');
guardRows = repmat(struct('CodeRate',"",'Rejected',false, ...
    'ErrorIdentifier',"",'Pass',false),numel(guardRates),1);
for iRate = 1:numel(guardRates)
    rate = guardRates(iRate);
    generator = ccsdsTMWaveformGenerator( ...
        'WaveformSource','synchronization and channel coding', ...
        'NumBytesInTransferFrame',1150,'Modulation','QPSK', ...
        'ChannelCoding','convolutional', ...
        'ConvolutionalCodeRate',char(rate),'HasASM',true, ...
        'RandomizerEnabled',false,'SamplesPerSymbol',8);
    rejected = false;
    identifier = "";
    try
        generator(zeros(generator.NumInputBits,1,'int8'));
    catch guardError
        identifier = string(guardError.identifier);
        rejected = identifier == ...
            "ccsdsTMWaveformGenerator:HighRateConvFrameLengthUnsupported";
    end
    guardRows(iRate) = struct('CodeRate',rate,'Rejected',rejected, ...
        'ErrorIdentifier',identifier,'Pass',rejected);
end
MainConvStreamHighRateLegacyGuard = struct2table(guardRows);
disp(MainConvStreamHighRateLegacyGuard);
assert(all(MainConvStreamHighRateLegacyGuard.Pass), ...
    'Legacy non-aligned frame guard was unintentionally disabled.');

function p = localBaseOptions(modType,tfBytes,warmupFrames, ...
        measurementFrames,phaseOffset)
p = struct( ...
    'modType',char(modType),'channelCoding','convolutional', ...
    'ConvolutionalG1G2Mode','auto-ccsds', ...
    'symbolRate',10e6,'sps',8,'snr',100,'noiseMode','off', ...
    'noisePlacement','afterChannel','cfo',0, ...
    'phaseOffset',phaseOffset,'delay',0, ...
    'RolloffFactor',0.35,'WaveformMode','ordinaryTM', ...
    'NumBytesInTransferFrame',tfBytes,'hasASM',true, ...
    'RandomizerEnabled',false,'RandomizerFECPosition','afterEncoding', ...
    'DataPathMode','single','TMDataSource','random','PCMFormat','NRZ-L', ...
    'berWarmUpFrames',warmupFrames,'berFrames',measurementFrames, ...
    'excludeBERWarmUpFrames',true,'enableHChannel',false,'HMode','none', ...
    'normalizeHChannel',false,'enableEqualizer',false, ...
    'equalizerMode','off','enableKnownHPreEqualizer',false, ...
    'normalizeEqualizerOutput',false,'enableConverterChain',false, ...
    'enableADCEquivalent',false,'inputLevelDbm',-10,'AGCEnabled',false, ...
    'showFigures',false,'showPipelineFigure',false, ...
    'showDamageBudgetFigure',false,'showPowerFigure',false, ...
    'debugCodedBoundary',false,'debugPerFrameBERSummary',false, ...
    'seed',5678);
end

function row = localResultRow(mode,modType,rate,tfBytes,p,m,expectedFrames)
coverage = isfield(m,'MeasurementCoverage') && ...
    strcmpi(string(m.MeasurementCoverage.Status),'COMPLETE') && ...
    m.MeasurementCoverage.ComparedFrames==expectedFrames && ...
    m.MeasurementCoverage.UnrecoveredFrames==0 && ...
    m.MeasurementCoverage.RecoveredNotComparedFrames==0;
streamMode = strcmp(mode,'stream-raw-asm');
available = localField(m,'ContinuousConvReceiverAvailable',NaN);
pass = logical(m.success) && m.BER==0 && m.FER==0 && coverage;
if streamMode
    pass = pass && logical(available) && ...
        localField(m,'ContinuousConvLongestGoodASMRun',0)>=4;
end
row = struct('Mode',string(mode),'ModType',string(modType), ...
    'CodeRate',string(rate), ...
    'TFBytes',tfBytes,'RawFrameRemainder',mod(32+8*tfBytes,p), ...
    'Success',logical(m.success),'ReceiverAvailable',available, ...
    'SelectedRotation_deg',localField(m, ...
        'PhaseAmbiguityRotation_deg',NaN), ...
    'SelectedOffset',localField(m,'ContinuousConvSelectedOffset',NaN), ...
    'LongestGoodASMRun',localField(m, ...
        'ContinuousConvLongestGoodASMRun',NaN), ...
    'RecoveredFrames',localField(m,'ContinuousConvRecoveredFrames',NaN), ...
    'BER',m.BER,'FER',m.FER, ...
    'ComparedFrames',m.MeasurementCoverage.ComparedFrames, ...
    'ExpectedFrames',m.MeasurementCoverage.ExpectedFrames, ...
    'UnrecoveredFrames',m.MeasurementCoverage.UnrecoveredFrames, ...
    'RecoveredNotComparedFrames', ...
        m.MeasurementCoverage.RecoveredNotComparedFrames, ...
    'CoverageStatus',string(m.MeasurementCoverage.Status), ...
    'Pass',logical(pass));
end

function localPrint(row)
fprintf(['  success=%d available=%g drop=%g run=%g recovered=%g ', ...
    'rot=%+.1f deg BER=%g FER=%g coverage=%g/%g ', ...
    'missing=%g extra=%g -> %s\n'], ...
    row.Success,row.ReceiverAvailable,row.SelectedOffset, ...
    row.LongestGoodASMRun,row.RecoveredFrames,row.SelectedRotation_deg, ...
    row.BER,row.FER, ...
    row.ComparedFrames,row.ExpectedFrames,row.UnrecoveredFrames, ...
    row.RecoveredNotComparedFrames,localPassLabel(row.Pass));
end

function value = localField(s,name,defaultValue)
value = defaultValue;
if isfield(s,name) && ~isempty(s.(name)), value=s.(name); end
end

function value = localNumber(s,name,defaultValue)
value = double(localField(s,name,defaultValue));
end

function value = localLogical(s,name,defaultValue)
value = logical(localField(s,name,defaultValue));
end

function label = localPassLabel(pass)
if pass, label='PASS'; else, label='FAIL'; end
end

function row = localEmptyRow()
row = struct('Mode',"",'ModType',"",'CodeRate',"",'TFBytes',NaN, ...
    'RawFrameRemainder',NaN,'Success',false, ...
    'ReceiverAvailable',NaN,'SelectedRotation_deg',NaN, ...
    'SelectedOffset',NaN, ...
    'LongestGoodASMRun',NaN,'RecoveredFrames',NaN, ...
    'BER',NaN,'FER',NaN,'ComparedFrames',NaN,'ExpectedFrames',NaN, ...
    'UnrecoveredFrames',NaN,'RecoveredNotComparedFrames',NaN, ...
    'CoverageStatus',"",'Pass',false);
end
