% CODEX_MODULATION_RATE_CONTRACT_SMOKE_V1
% Verify that the public equipment-style Mbps input drives the real MATLAB
% DSP symbol rate.  This is not a standalone formula-only test.

scriptDir = fileparts(mfilename('fullpath'));
projectDir = fileparts(scriptDir);
addpath(fullfile(projectDir,'src','python'));

p = struct( ...
    'modType','16QAM', ...
    'modulatorBitRateMbps',40, ... % 4 bit/symbol -> 10 Msym/s
    'sps',8, ...
    'channelCoding','none', ...
    'NumBytesInTransferFrame',128, ...
    'hasASM',true, ...
    'RandomizerEnabled',false, ...
    'DataPathMode','single', ...
    'PCMFormat','NRZ-L', ...
    'noiseMode','off', ...
    'snr',100, ...
    'cfo',0, ...
    'phaseOffset',0, ...
    'delay',0, ...
    'RolloffFactor',0.35, ...
    'berWarmUpFrames',2, ...
    'berFrames',4, ...
    'enableHChannel',false, ...
    'enableEqualizer',false, ...
    'showFigures',false, ...
    'remoteMode',false, ...
    'includeRawData',false, ...
    'seed',260923);

[RateContractResult,~] = run_ccsds_tm_evaluation(p);
assert(RateContractResult.success,RateContractResult.errorMsg);
assert(abs(RateContractResult.ModulatorBitRate_bps-40e6)<1);
assert(abs(RateContractResult.SymbolRate_Hz-10e6)<1);
assert(abs(RateContractResult.NominalBitsPerSymbol-4)<eps);
assert(strcmp(RateContractResult.RateInputMode,'modulator-bit-rate'));

fprintf('\n================ MODULATION RATE CONTRACT ================\n');
fprintf('Input modulation rate : %.6f Mbps\n', ...
    RateContractResult.ModulatorBitRate_bps/1e6);
fprintf('Mapper bits/symbol    : %.6f\n', ...
    RateContractResult.NominalBitsPerSymbol);
fprintf('Resolved symbol rate  : %.6f Msym/s\n', ...
    RateContractResult.SymbolRate_Hz/1e6);
fprintf('Sample rate           : %.6f MHz\n', ...
    RateContractResult.Fs/1e6);
fprintf('BER / FER             : %.6g / %.6g\n', ...
    RateContractResult.BER,RateContractResult.FER);
fprintf('PASS: equipment-style Mbps input reached the MATLAB DSP chain.\n');
