%% BPSK/QPSK/8PSK + TPC 1/2 A4 extra-tracker A/B diagnosis
% This is a receiver-front-end diagnosis, not a final decoded-BER test.
% It preserves the TPC 1/2 x8 waveform and uses the hard-systematic decoder
% bypass so that the same physical A4 interval can be compared quickly.
%
% Optional caller variable:
%   PSKTrackerABOptions = struct(...)
% Useful fields:
%   ModTypes         default ["BPSK";"QPSK";"8PSK"]
%   PhaseModes       default ["legacy-dual";"off"]
%   TargetDuration_s default 0.082
%   StartFile        default 4 (CDL A4)
%   ReceiverOverrides optional receiver fields for one-variable A/B tests
%
% Results stay in PSKTrackerABResults / PSKTrackerABLogs. No file is saved.

if exist('PSKTrackerABOptions','var') && isstruct(PSKTrackerABOptions)
    pskABOptions = PSKTrackerABOptions;
else
    pskABOptions = struct();
end

pskABSweepFile = [ ...
    'E:/web_code/react/fft_project/react-fft/tmp/' ...
    'codex_new_channel_psd_sync_sweep_v1.m'];

pskABModTypes = ["BPSK";"QPSK";"8PSK"];
pskABPhaseModes = ["legacy-dual";"off"];
pskABTargetDuration_s = 0.082;
pskABStartFile = 4;
if isfield(pskABOptions,'ModTypes') && ~isempty(pskABOptions.ModTypes)
    pskABModTypes = string(pskABOptions.ModTypes(:));
end
if isfield(pskABOptions,'PhaseModes') && ~isempty(pskABOptions.PhaseModes)
    pskABPhaseModes = string(pskABOptions.PhaseModes(:));
end
if isfield(pskABOptions,'TargetDuration_s')
    pskABTargetDuration_s = double(pskABOptions.TargetDuration_s);
end
if isfield(pskABOptions,'StartFile')
    pskABStartFile = round(double(pskABOptions.StartFile));
end
if ~isscalar(pskABTargetDuration_s) || ~isfinite(pskABTargetDuration_s) || ...
        pskABTargetDuration_s <= 0
    error('codex_psk_tpc_a4_tracker_ab:InvalidDuration', ...
        'TargetDuration_s must be a positive finite scalar.');
end

pskABNumCases = numel(pskABModTypes)*numel(pskABPhaseModes);
pskABRows = cell(pskABNumCases,1);
PSKTrackerABLogs = cell(pskABNumCases,1);
pskABCaseIndex = 0;

% TPC 1/2 x8 produces eight 64x64 product-code blocks per transfer frame.
pskABCodedBitsPerFrame = 8*64*64;
pskABSymbolRate = 30e6;

for pskABModIndex = 1:numel(pskABModTypes)
    pskABModType = upper(strtrim(pskABModTypes(pskABModIndex)));
    switch pskABModType
        case "BPSK"
            pskABBitsPerSymbol = 1;
        case "QPSK"
            pskABBitsPerSymbol = 2;
        case "8PSK"
            pskABBitsPerSymbol = 3;
        otherwise
            error('codex_psk_tpc_a4_tracker_ab:UnsupportedModulation', ...
                'ModTypes supports only BPSK, QPSK, and 8PSK.');
    end

    pskABFrameDuration_s = pskABCodedBitsPerFrame/( ...
        pskABBitsPerSymbol*pskABSymbolRate);
    pskABTotalFrames = max(5,ceil( ...
        pskABTargetDuration_s/pskABFrameDuration_s));
    pskABWarmUpFrames = max(1,round(0.20*pskABTotalFrames));
    pskABBERFrames = pskABTotalFrames-pskABWarmUpFrames;

    for pskABModeIndex = 1:numel(pskABPhaseModes)
        pskABPhaseMode = lower(strtrim(pskABPhaseModes(pskABModeIndex)));
        pskABCaseIndex = pskABCaseIndex+1;
        fprintf('\n====================================================\n');
        fprintf(' PSK/TPC tracker A/B %d/%d: %s + %s\n', ...
            pskABCaseIndex,pskABNumCases,pskABModType,pskABPhaseMode);
        fprintf(' frames=%d+%d, target/nominal duration=%.3f/%.3f ms\n', ...
            pskABWarmUpFrames,pskABBERFrames, ...
            1e3*pskABTargetDuration_s, ...
            1e3*pskABTotalFrames*pskABFrameDuration_s);
        fprintf('====================================================\n');

        pskABReceiver = struct( ...
            'channelPathPowerMode','embedded', ...
            'adaptiveEqualizerSamplingMode','2sps', ...
            'adaptiveFractionalEqualizerTaps',129, ...
            'adaptiveFractionalEqualizerStep',2e-4, ...
            'adaptiveFractionalEqualizerWeightUpdatePeriod',1, ...
            'adaptiveFractionalPostMode','off', ...
            'TPCCodeRate','1/2', ...
            'TPCBlocksPerTF',8, ...
            'TPCInterleaver','auto', ...
            'TPCUseKnownZeroConstraint',false, ...
            'TPCDecoderMode','hard-systematic-debug', ...
            'PSKPostFSEPhaseTrackerMode',char(pskABPhaseMode), ...
            'collectPredecoderStats',true, ...
            'debugCodedBoundary',false, ...
            'debugPredecoderBurst',false, ...
            'debugTPCCaptureWorstCodeword',false, ...
            'debugAdaptiveEqualizer',false);
        if isfield(pskABOptions,'ReceiverOverrides') && ...
                isstruct(pskABOptions.ReceiverOverrides)
            pskABOverrideNames = fieldnames(pskABOptions.ReceiverOverrides);
            for pskABOverrideIndex = 1:numel(pskABOverrideNames)
                pskABOverrideName = pskABOverrideNames{pskABOverrideIndex};
                pskABReceiver.(pskABOverrideName) = ...
                    pskABOptions.ReceiverOverrides.(pskABOverrideName);
            end
        end
        % These two fields define the diagnostic itself and cannot be
        % accidentally replaced by a generic receiver override.
        pskABReceiver.PSKPostFSEPhaseTrackerMode = char(pskABPhaseMode);
        pskABReceiver.TPCDecoderMode = 'hard-systematic-debug';

        NewChannelPSDSweepOptions = struct( ...
            'StartFile',pskABStartFile, ...
            'MaxFiles',1, ...
            'ModType',char(pskABModType), ...
            'ChannelCoding','TPC', ...
            'NumBytesInTransferFrame',1115, ...
            'SymbolRate',pskABSymbolRate, ...
            'SamplesPerSymbol',8, ...
            'BERWarmUpFrames',pskABWarmUpFrames, ...
            'BERFrames',pskABBERFrames, ...
            'NoiseMode','off', ...
            'NormalizeHChannel',true, ...
            'ChannelSampleRateHz',1e5, ...
            'ReceiverOverrides',pskABReceiver, ...
            'VerboseReceiverLog',false, ...
            'SaveCSV',false);

        run(pskABSweepFile);
        pskABRow = NewChannelPSDSweepResults(1,:);
        pskABRow.TestModType = pskABModType;
        pskABRow.TestPhaseMode = pskABPhaseMode;
        pskABRow.DiagnosticOnly = true;
        pskABRow.ConfiguredWarmUpFrames = pskABWarmUpFrames;
        pskABRow.ConfiguredBERFrames = pskABBERFrames;
        pskABRow.NominalDuration_s = ...
            pskABTotalFrames*pskABFrameDuration_s;
        pskABRow.WorstFrameMidpoint_ms = ...
            (pskABRow.PredecoderWorstFrameIndex-0.5)* ...
            (1e3*pskABRow.WaveformDuration_s/pskABTotalFrames);
        pskABRows{pskABCaseIndex} = pskABRow;
        PSKTrackerABLogs{pskABCaseIndex} = ...
            NewChannelPSDSweepLogs{1};
    end
end

PSKTrackerABResults = vertcat(pskABRows{:});

fprintf('\n================ PSK/TPC A4 TRACKER A/B ================\n');
disp(PSKTrackerABResults(:,{ ...
    'TestModType','TestPhaseMode','PSKPostFSEPhaseTrackerMode', ...
    'WaveformDuration_s','BER','FER','PredecoderSteadyBER', ...
    'PredecoderNonzeroErrorFrames','PredecoderFrameBERP95', ...
    'PredecoderFrameBERMax','PredecoderWorstFrameIndex', ...
    'PredecoderWorstFrameBitErrors', ...
    'PredecoderWorstFrameTPCMaxCodewordErrors', ...
    'PredecoderWorstFrameTPCNonzeroCodewords', ...
    'WorstFrameMidpoint_ms','ASMFramePhaseCorrectionApplied', ...
    'ASMFramePhaseCorrectionFrames', ...
    'ASMFramePhaseCorrectionReliableFrames', ...
    'ASMFramePhaseCycleSlipsBefore', ...
    'ASMFramePhaseCycleSlipsAfter','FSEErrorMSE','FrameLock_pct'}));

fprintf(['\nInterpretation: BER/FER are hard systematic-bit diagnostics, ', ...
    'not final iterative TPC results.\n']);
fprintf(['Compare legacy-dual with off within each modulation. Only treat ', ...
    'off as a candidate default when it removes no-H/A4 regressions, ', ...
    'does not add phase slips, and does not worsen predecoder tails.\n']);
fprintf('No files were written.\n');
