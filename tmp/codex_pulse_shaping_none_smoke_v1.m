% Public RRC/none pulse-shaping contract smoke test.
dbclear all;
clear functions;
rehash;
addpath('E:/web_code/react/fft_project/react-fft/src/python');

mods = ["QPSK";"BPSK";"QPSK";"8PSK";"16QAM";"32QAM"];
modes = ["root raised cosine";repmat("none",5,1)];
tfBytes = [256;256;256;254;256;256];
rows = repmat(struct(),numel(mods),1);
for k = 1:numel(mods)
    fprintf('\n[pulse shaping %d/%d] %s + %s\n', ...
        k,numel(mods),mods(k),modes(k));
    p = struct( ...
        'modType',char(mods(k)), ...
        'symbolRate',10e6, ...
        'sps',8, ...
        'channelCoding','none', ...
        'NumBytesInTransferFrame',tfBytes(k), ...
        'hasASM',true, ...
        'RandomizerEnabled',false, ...
        'DataPathMode','single', ...
        'PCMFormat','NRZ-L', ...
        'PulseShapingFilter',char(modes(k)), ...
        'RolloffFactor',0.35, ...
        'FilterSpanInSymbols',10, ...
        'noiseMode','off', ...
        'cfo',0, ...
        'phaseOffset',0, ...
        'delay',0, ...
        'berWarmUpFrames',4, ...
        'berFrames',12, ...
        'excludeBERWarmUpFrames',true, ...
        'enableHChannel',false, ...
        'enableEqualizer',false, ...
        'showFigures',false);
    m = run_ccsds_tm_evaluation(p);
    assert(m.success,'%s',m.errorMsg);
    rows(k).Modulation = mods(k);
    rows(k).Requested = modes(k);
    rows(k).Actual = string(m.PulseShapingFilter);
    rows(k).TX = string(m.TransmitPulseShapeActual);
    rows(k).RX = string(m.ReceivePulseFilterActual);
    rows(k).BER = m.BER;
    rows(k).FER = m.FER;
    rows(k).Frames = m.CountedFrames;
    rows(k).Coverage = string(m.MeasurementCoverage.Status);
    rows(k).CoverageComplete = logical(m.MeasurementCoverage.Complete);
    rows(k).UnrecoveredFrames = m.MeasurementCoverage.UnrecoveredFrames;
    assert(rows(k).Actual == modes(k), ...
        'Requested pulse-shaping mode was not honored.');
    assert(m.BER == 0 && m.FER == 0, ...
        'No-H/no-noise pulse-shaping regression must have BER=FER=0.');
    assert(m.CountedFrames >= p.berFrames, ...
        'Pulse-shaping regression did not compare all requested measurement frames.');
    assert(m.MeasurementCoverage.UnrecoveredFrames == 0, ...
        'Pulse-shaping regression contains unrecovered frames.');
    assert(rows(k).CoverageComplete, ...
        'Pulse-shaping regression must have complete measurement coverage.');
end

PulseShapingNoneSmoke = struct2table(rows);
disp(PulseShapingNoneSmoke);
fprintf(['PASS: QPSK RRC baseline and all five public none paths have complete ', ...
    'measurement coverage with zero BER/FER and no unrecovered frames.\n']);
