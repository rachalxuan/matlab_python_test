%% QPSK + TPC 1/2 A4 phase-path diagnosis (fast, decoder bypass)
% This is an evidence-gathering A/B/C test, not a BER qualification run.
% It preserves the exact TPC 1/2 x8 waveform, interleaver, frame duration,
% channel, FSE and ASM correction, but extracts the received systematic TPC
% bits instead of invoking the slow iterative Chase decoder.
%
% Compared QPSK post-FSE phase routes:
%   legacy-dual : historical fourth-power tracker before and after post-EQ
%   single-post : only the final fourth-power tracker
%   off         : neither extra tracker (ordinary carrier sync remains on)
%
% Results remain in QPSKTPCPhaseDiagnosisResults / Logs.  No file is saved.

if exist('QPSKTPCPhaseDiagnosisOptions','var') && ...
        isstruct(QPSKTPCPhaseDiagnosisOptions)
    diagnosisOptions = QPSKTPCPhaseDiagnosisOptions;
else
    diagnosisOptions = struct();
end

sweepFile = [ ...
    'E:/web_code/react/fft_project/react-fft/tmp/' ...
    'codex_new_channel_psd_sync_sweep_v1.m'];

phaseModes = ["legacy-dual";"single-post";"off"];
if isfield(diagnosisOptions,'PhaseModes') && ...
        ~isempty(diagnosisOptions.PhaseModes)
    phaseModes = string(diagnosisOptions.PhaseModes(:));
end
numModes = numel(phaseModes);
diagnosisRows = cell(numModes,1);
QPSKTPCPhaseDiagnosisLogs = cell(numModes,1);

warmUpFrames = 30;
berFrames = 120;
startFile = 4;
if isfield(diagnosisOptions,'BERWarmUpFrames')
    warmUpFrames = round(double(diagnosisOptions.BERWarmUpFrames));
end
if isfield(diagnosisOptions,'BERFrames')
    berFrames = round(double(diagnosisOptions.BERFrames));
end
if isfield(diagnosisOptions,'StartFile')
    startFile = round(double(diagnosisOptions.StartFile));
end
totalFrames = warmUpFrames + berFrames;

for iPhaseMode = 1:numModes
    phaseMode = phaseModes(iPhaseMode);
    fprintf('\n====================================================\n');
    fprintf(' QPSK/TPC A4 phase diagnosis %d/%d: %s\n', ...
        iPhaseMode,numModes,phaseMode);
    fprintf('====================================================\n');

    rx = struct( ...
        'channelPathPowerMode','embedded', ...
        'adaptiveEqualizerSamplingMode','2sps', ...
        'adaptiveFractionalEqualizerTaps',129, ...
        'adaptiveFractionalEqualizerStep',2e-4, ...
        'adaptiveFractionalEqualizerWeightUpdatePeriod',1, ...
        'adaptiveFractionalPostMode','off', ...
        'TPCCodeRate','1/2', ...
        'TPCBlocksPerTF',8, ...
        'TPCInterleaver','auto', ...
        'TPCUseKnownZeroConstraint',false, ...
        'TPCDecoderMode','hard-systematic-debug', ...
        'QPSKPostFSEPhaseTrackerMode',char(phaseMode), ...
        'collectPredecoderStats',true, ...
        'debugCodedBoundary',false, ...
        'debugPredecoderBurst',false, ...
        'debugTPCCaptureWorstCodeword',true, ...
        'debugAdaptiveEqualizer',false);

    NewChannelPSDSweepOptions = struct( ...
        'StartFile',startFile, ...
        'MaxFiles',1, ...
        'ModType','QPSK', ...
        'ChannelCoding','TPC', ...
        'NumBytesInTransferFrame',1115, ...
        'SymbolRate',30e6, ...
        'SamplesPerSymbol',8, ...
        'BERWarmUpFrames',warmUpFrames, ...
        'BERFrames',berFrames, ...
        'NoiseMode','off', ...
        'NormalizeHChannel',true, ...
        'ChannelSampleRateHz',1e5, ...
        'ReceiverOverrides',rx, ...
        'VerboseReceiverLog',false, ...
        'SaveCSV',false);

    run(sweepFile);
    row = NewChannelPSDSweepResults(1,:);
    row.TestPhaseMode = phaseMode;
    row.DiagnosticOnly = true;
    row.FrameDuration_ms = 1e3*row.WaveformDuration_s/totalFrames;
    row.WorstFrameMidpoint_ms = ...
        (row.PredecoderWorstFrameIndex-0.5)*row.FrameDuration_ms;
    row.WorstCodewordDecodedErrors = NaN;
    row.WorstCodewordDecoderElapsed_s = NaN;
    if exist('debugTPCWorstCodewordCapture','var') && ...
            isstruct(debugTPCWorstCodewordCapture)
        capture = debugTPCWorstCodewordCapture;
        decodeTimer = tic;
        decoded = ccsdsTPCDecodeSoft(capture.Soft, ...
            'TPCCodeRate','1/2', ...
            'TPCInterleaver','auto', ...
            'UseKnownZeroConstraint',false, ...
            'DecoderMode','iterative');
        expected = ccsdsTPCDecodeSoft( ...
            2*double(capture.TransmittedBits)-1, ...
            'TPCCodeRate','1/2', ...
            'TPCInterleaver','auto', ...
            'DecoderMode','hard-systematic-debug');
        row.WorstCodewordDecodedErrors = ...
            double(nnz(decoded ~= expected));
        row.WorstCodewordDecoderElapsed_s = toc(decodeTimer);
    end
    diagnosisRows{iPhaseMode} = row;
    QPSKTPCPhaseDiagnosisLogs{iPhaseMode} = ...
        NewChannelPSDSweepLogs{1};
end

QPSKTPCPhaseDiagnosisResults = vertcat(diagnosisRows{:});

fprintf('\n================ QPSK/TPC A4 PHASE DIAGNOSIS ================\n');
disp(QPSKTPCPhaseDiagnosisResults(:,{ ...
    'TestPhaseMode','TPCDecoderMode','WaveformDuration_s', ...
    'BER','FER','PredecoderSteadyBER', ...
    'PredecoderNonzeroErrorFrames','PredecoderFrameBERP95', ...
    'PredecoderFrameBERMax','PredecoderWorstFrameIndex', ...
    'PredecoderWorstFrameBitErrors','PredecoderCodedBitsPerFrame', ...
    'PredecoderWorstFrameTPCMaxCodewordErrors', ...
    'PredecoderWorstFrameTPCNonzeroCodewords', ...
    'WorstCodewordDecodedErrors','WorstCodewordDecoderElapsed_s', ...
    'WorstFrameMidpoint_ms','ASMFramePhaseCycleSlipsBefore', ...
    'ASMFramePhaseCycleSlipsAfter','FSEErrorMSE', ...
    'FrameLock_pct'}));

fprintf(['\nInterpretation: BER/FER above are hard systematic-bit diagnostics, ', ...
    'not decoded TPC performance.\n']);
fprintf(['If all three modes fail at the same frame/time with similar ', ...
    'predecoder maxima, the extra QPSK tracker is not the cause.\n']);
fprintf(['If single-post or off removes the slip and materially lowers both ', ...
    'steady and worst-frame BER, repeat only that winner once with ', ...
    'TPCDecoderMode="iterative".\n']);
fprintf('No files were written.\n');
