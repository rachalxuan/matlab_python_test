clearvars; clear classes; rehash;
rootDir = 'E:/web_code/react/fft_project/react-fft';
addpath(fullfile(rootDir, 'src/python'), '-begin');

mods = {'GMSK','16QAM'};
randomizers = [false true];
rows = cell(0,8);
for iMod = 1:numel(mods)
    for iRand = 1:numel(randomizers)
        p = struct( ...
            'modType',mods{iMod}, ...
            'symbolRate',10e6, ...
            'sps',8, ...
            'channelCoding','TPC', ...
            'TPCCodeRate','1/2', ...
            'TPCBlocksPerTF',8, ...
            'TPCInterleaver','auto', ...
            'hasASM',true, ...
            'RandomizerEnabled',randomizers(iRand), ...
            'RandomizerFECPosition','afterEncoding', ...
            'berWarmUpFrames',2, ...
            'berFrames',6, ...
            'excludeBERWarmUpFrames',true, ...
            'enableHChannel',false, ...
            'noisePlacement','afterChannel', ...
            'noiseMode','psd', ...
            'noisePSDdBmHz',-115.3, ...
            'noiseBandwidthHz',[], ...
            'inputLevelDbm',-10, ...
            'equalizerMode','blind-cma-lms', ...
            'enableQAMBlindPhaseSearch',true, ...
            'enableQAMBlindPhaseSearchForTPC',false, ...
            'GMSKDetectionMode','official-viterbi-frame-reset', ...
            'collectPredecoderStats',true, ...
            'debugCodedBoundary',true, ...
            'debugAdaptiveEqualizer',true, ...
            'showFigures',false);
        rng(20260824, 'twister');
        [m,~] = run_ccsds_tm_evaluation(p);
        rows(end+1,:) = {string(mods{iMod}),randomizers(iRand), ...
            m.BER,m.PredecoderBER,100*m.LockRate,m.FER, ...
            m.QAMBlindPhaseSearchApplied,string(m.GMSKDetectorUsed)}; %#ok<AGROW>
    end
end

T = cell2table(rows, 'VariableNames', {'ModType','RandomizerEnabled', ...
    'BER','PredecoderBER','LockRate_pct','FER', ...
    'QAMBlindPhaseSearchApplied','GMSKDetectorUsed'});
disp(T);
assert(all(T.BER == 0), 'TPC public-path smoke test has nonzero BER.');
assert(all(T.FER == 0), 'TPC public-path smoke test has nonzero FER.');
assert(all(T.LockRate_pct >= 90), 'TPC public-path smoke test did not lock.');
assert(~any(T.QAMBlindPhaseSearchApplied), ...
    'QAM BPS was unexpectedly applied to a TPC case.');
